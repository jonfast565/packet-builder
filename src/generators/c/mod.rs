//! C backend: a single-header library (C99). Define `<PACKAGE>_IMPLEMENTATION`
//! in exactly one translation unit before including the header.

mod decode;
mod encode;
mod expr;
mod json;
mod naming;
mod packet;
mod stream;

pub use naming::{ident, len_ident, scalar_type};
pub use packet::arm_kind;

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out};
use crate::ir::{Category, Constant, Module, ValueType};

pub struct CGenerator;

const RUNTIME_DECL: &str = include_str!("../../../runtime/c_decl.h");
const RUNTIME_IMPL: &str = include_str!("../../../runtime/c_impl.h");

impl Backend for CGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let guard = opts.package.to_ascii_uppercase().replace(|c: char| !c.is_ascii_alphanumeric(), "_");
        let mut out = Out::new("    ");
        out.line("/* Generated by packet-builder. Do not edit.");
        out.line(" *");
        out.line(format!(" * In exactly one .c file: #define {}_IMPLEMENTATION before #include.", guard));
        out.line(" * Decoders allocate arrays with malloc; release them with <Packet>_free().");
        out.line(" * Encoders return a malloc'ed buffer that the caller frees with free().");
        out.line(" */");
        out.line(format!("#ifndef {}_H", guard));
        out.line(format!("#define {}_H", guard));
        out.line("");
        out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME_DECL, module.versions.is_some()));
        self.emit_constants(&mut out, module);
        out.line("");
        out.line("#ifdef __cplusplus");
        out.line("extern \"C\" {");
        out.line("#endif");
        // Every type first, so that arrays (pointers) may refer to packets
        // defined later.
        out.line("");
        for u in &module.unions {
            out.line(format!("typedef struct {} {};", u.name, u.name));
        }
        for p in &module.packets {
            out.line(format!("typedef struct {} {};", p.name, p.name));
        }
        for p in module.in_dependency_order() {
            for m in &p.members {
                if let ValueType::Union(n) = &m.ty
                    && let Some(u) = module.union(n)
                {
                    out.line("");
                    packet::emit_union_declaration(&mut out, u, opts.zero_copy);
                }
            }
            out.line("");
            packet::emit_declarations(&mut out, p, opts.zero_copy);
            stream::declare_streaming(&mut out, module, p);
            json::declare_json(&mut out, p);
        }
        out.line("");
        out.line("#ifdef __cplusplus");
        out.line("}");
        out.line("#endif");
        out.line("");
        out.line(format!("#endif /* {}_H */", guard));
        out.line("");
        out.line(format!("#ifdef {}_IMPLEMENTATION", guard));
        out.line(format!("#ifndef {}_IMPLEMENTED", guard));
        out.line(format!("#define {}_IMPLEMENTED", guard));
        out.line("");
        out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME_IMPL, module.versions.is_some()));
        json::emit_json_prototypes(&mut out, module);
        for u in &module.unions {
            out.line("");
            packet::emit_union_free(&mut out, u, opts.zero_copy);
            json::emit_union_json(&mut out, u);
        }
        for p in &module.packets {
            out.line("");
            packet::emit_implementation(&mut out, p, opts.zero_copy);
            stream::emit_streaming(&mut out, module, p);
            json::emit_packet_json(&mut out, p);
        }
        out.line("");
        out.line(format!("#endif /* {}_IMPLEMENTED */", guard));
        out.line(format!("#endif /* {}_IMPLEMENTATION */", guard));
        out.buf
    }
}

/// `#define NAME ((uint8_t)1u)`, with the note as a comment.
fn define(out: &mut Out, name: &str, c: &Constant) {
    if let Some(note) = &c.note {
        out.line(format!("/* {} */", note.replace("*/", "* /")));
    }
    let wide = matches!(c.ty, ValueType::Int { width: 33.., .. });
    let value = match (c.ty.is_signed(), wide) {
        (true, true) if c.value == i64::MIN => "INT64_MIN".to_string(),
        (true, true) => format!("{}LL", c.literal()),
        (true, false) => c.literal(),
        (false, true) => format!("{}ULL", c.literal()),
        (false, false) => format!("{}u", c.literal()),
    };
    out.line(format!("#define {} (({}){})", name, scalar_type(&c.ty), value));
}

impl ConstEmitter for CGenerator {
    fn constant(&self, out: &mut Out, c: &Constant) {
        define(out, &c.name.to_ascii_uppercase(), c);
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.line(format!("/* {} values */", cat.name));
        for c in &cat.members {
            define(out, &format!("{}_{}", cat.name, c.name).to_ascii_uppercase(), c);
        }
    }
}
