//! Python backend: a single module using only the standard library.

mod decode;
mod encode;
mod expr;
mod json;
mod naming;
mod packet;
mod stream;

pub use naming::ident;

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out};
use crate::ir::{Category, Constant, Module};

pub struct PythonGenerator;

const RUNTIME: &str = include_str!("../../../runtime/python.py");

impl Backend for PythonGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let mut out = Out::new("    ");
        out.line("# Generated by packet-builder. Do not edit.");
        out.line("from __future__ import annotations");
        out.line("");
        out.line("import json");
        out.line("import math");
        out.line("import struct");
        out.line("from dataclasses import dataclass, field");
        out.line("from typing import List, Optional, Tuple");
        out.line("");
        out.line("");
        out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME, module.versions.is_some()));
        self.emit_constants(&mut out, module);
        for u in &module.unions {
            out.line("");
            out.line("");
            packet::emit_union(&mut out, u);
        }
        for p in &module.packets {
            out.line("");
            out.line("");
            packet::emit_packet(&mut out, module, p, opts.zero_copy);
        }
        out.buf
    }
}

impl ConstEmitter for PythonGenerator {
    fn separator(&self, out: &mut Out) {
        out.line("");
        out.line("");
    }

    /// Upper case, so a module-level constant never shadows a builtin.
    fn constant(&self, out: &mut Out, c: &Constant) {
        if let Some(note) = &c.note {
            out.line(format!("# {}", note));
        }
        out.line(format!("{} = {}", c.name.to_ascii_uppercase(), c.literal()));
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.open(format!("class {}:", ident(&cat.name)));
        out.line(format!("\"\"\"Named `{}` values.\"\"\"", cat.name));
        out.line("");
        for c in &cat.members {
            if let Some(note) = &c.note {
                out.line(format!("# {}", note));
            }
            out.line(format!("{} = {}", c.name.to_ascii_uppercase(), c.literal()));
        }
        out.pop();
    }
}
