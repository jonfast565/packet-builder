//! Lua backend: one module (Lua 5.3+, no C modules) that returns a table
//! of packet classes. Byte buffers are Lua strings, which are immutable and
//! shared, so `--zero-copy` changes nothing.

mod decode;
mod encode;
mod expr;
mod json;
mod naming;
mod packet;
mod stream;

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out};
use crate::ir::{Category, Constant, Module};

pub use naming::Lua;

pub struct LuaGenerator;

const RUNTIME: &str = include_str!("../../../runtime/lua.lua");

impl Backend for LuaGenerator {
    fn generate(&self, module: &Module, _opts: &GenOptions) -> String {
        let mut out = Out::new("  ");
        out.line("-- Generated by packet-builder. Do not edit.");
        out.line("--");
        out.line("-- local packets = require(\"packets\")");
        out.line("-- local p = packets.Name.decode(data)      -- raises a PbError (use pcall)");
        out.line("-- local p, err = packets.Name.decode_safe(data)");
        out.line("-- local bytes = packets.Name.encode(p)");
        out.line("");
        out.buf.push_str(&crate::generators::common::lua::runtime(RUNTIME, module.versions.is_some()));
        out.line("");
        out.line("local M = { PbError = PbErr }");
        self.emit_constants(&mut out, module);
        for u in &module.unions {
            out.line("");
            packet::emit_union(&mut out, u);
        }
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, module, p);
        }
        out.line("");
        out.line("return M");
        out.buf
    }
}

/// A constant's name in the module table: upper case, like Python's.
fn const_entry(c: &Constant) -> String {
    format!("{}{}", naming::key(&c.name.to_ascii_uppercase()), expr::const_literal(c))
}

impl ConstEmitter for LuaGenerator {
    fn constant(&self, out: &mut Out, c: &Constant) {
        if let Some(note) = &c.note {
            out.line(format!("-- {}", note));
        }
        out.line(format!("M.{}", const_entry(c)));
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.line(format!("-- Named `{}` values.", cat.name));
        out.open(format!("{} = {{", naming::class(&cat.name)));
        for c in &cat.members {
            if let Some(note) = &c.note {
                out.line(format!("-- {}", note));
            }
            out.line(format!("{},", const_entry(c)));
        }
        out.close("}");
    }
}
