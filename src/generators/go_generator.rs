//! Go backend: one file, standard library only (Go 1.18+ for generics).

use crate::generators::common::{ExprLang, GenOptions, Mode, Out, emit_expr, is_calc, mask, pascal_case};
use crate::ir::{
    AggOp, ArithOp, Codec, Count, Func, Member, MemberKind, Module, Packet, Step, StrMode, TExpr, Ty, ValueType,
};
use crate::models::parsing_models::Endianness;

pub struct GoGenerator;

const RUNTIME: &str = include_str!("../../runtime/go.go");

/// Exported Go field name for a member.
pub fn field_name(name: &str) -> String {
    let n = pascal_case(name);
    match n.as_str() {
        "DecodeFrom" | "Encode" | "EncodeTo" => format!("{}_", n),
        _ => n,
    }
}

pub fn scalar_type(ty: &ValueType) -> String {
    match ty {
        ValueType::Int { width, signed } => {
            format!("{}int{}", if *signed { "" } else { "u" }, crate::ir::storage_for(*width))
        }
        ValueType::Float { width } => format!("float{}", width),
        ValueType::Mac => "[6]byte".into(),
        ValueType::Packet(n) => n.clone(),
        ValueType::Str => "string".into(),
    }
}

pub fn member_type(m: &Member) -> String {
    match m.array {
        Some(_) => format!("[]{}", scalar_type(&m.ty)),
        None => scalar_type(&m.ty),
    }
}

impl GoGenerator {
    pub fn generate(module: &Module, opts: &GenOptions) -> String {
        let mut out = Out::new("\t");
        out.line("// Code generated by packet-builder. DO NOT EDIT.");
        out.line("");
        out.line(format!("package {}", opts.package));
        out.line("");
        out.line("import (");
        out.line("\t\"fmt\"");
        out.line("\t\"math\"");
        out.line("\t\"unicode/utf8\"");
        out.line(")");
        out.line("");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            emit_packet(&mut out, p);
        }
        out.buf
    }
}

fn little(e: &Endianness) -> &'static str {
    if *e == Endianness::Le { "true" } else { "false" }
}

struct Lang<'a> {
    packet: &'a Packet,
    mode: Mode,
}

impl<'a> Lang<'a> {
    fn place(&self, member: usize) -> String {
        let m = &self.packet.members[member];
        if self.mode == Mode::Encode && is_calc(m) {
            format!("pbc_{}", m.name)
        } else {
            format!("p.{}", field_name(&m.name))
        }
    }
}

impl<'a> ExprLang for Lang<'a> {
    fn int_lit(&self, v: i64) -> String {
        format!("int64({})", v)
    }

    fn float_lit(&self, v: f64) -> String {
        format!("float64({:?})", v)
    }

    fn member_ref(&self, member: usize, ty: Ty) -> String {
        let t = if ty == Ty::Float { "float64" } else { "int64" };
        format!("{}({})", t, self.place(member))
    }

    fn index(&self, member: usize, index: String, ty: Ty) -> String {
        let t = if ty == Ty::Float { "float64" } else { "int64" };
        format!("{}(pbAt({}, {}))", t, self.place(member), index)
    }

    fn aggregate(&self, member: usize, op: AggOp, ty: Ty) -> String {
        let f = match (op, ty) {
            (AggOp::Sum, Ty::Float) => "pbSumF",
            (AggOp::Product, Ty::Float) => "pbProdF",
            (AggOp::Sum, _) => "pbSum",
            (AggOp::Product, _) => "pbProd",
        };
        format!("{}({})", f, self.place(member))
    }

    fn arith(&self, op: ArithOp, a: String, b: String, ty: Ty) -> String {
        match (op, ty) {
            (ArithOp::Add, _) => format!("({} + {})", a, b),
            (ArithOp::Sub, _) => format!("({} - {})", a, b),
            (ArithOp::Mul, _) => format!("({} * {})", a, b),
            (ArithOp::Div, Ty::Float) => format!("pbFDiv({}, {})", a, b),
            (ArithOp::Div, _) => format!("pbDiv({}, {})", a, b),
            (ArithOp::Pow, Ty::Float) => format!("math.Pow({}, {})", a, b),
            (ArithOp::Pow, _) => format!("pbPow({}, {})", a, b),
        }
    }

    fn guard(&self, cond: String, then: String, other: String, _ty: Ty) -> String {
        format!("pbIf({}, {}, {})", cond, then, other)
    }

    fn call(&self, func: Func, args: Vec<String>, _ty: Ty) -> String {
        match func {
            Func::Sqrt => format!("math.Sqrt({})", args[0]),
            Func::Min => format!("pbMin({}, {})", args[0], args[1]),
            Func::Max => format!("pbMax({}, {})", args[0], args[1]),
        }
    }

    fn convert(&self, e: String, from: Ty, to: Ty) -> String {
        match (from, to) {
            (Ty::Bool, Ty::Int) => format!("pbB2I({})", e),
            (Ty::Bool, Ty::Float) => format!("float64(pbB2I({}))", e),
            (Ty::Int, Ty::Float) => format!("float64({})", e),
            (Ty::Float, Ty::Int) => format!("int64({})", e),
            (Ty::Int, Ty::Bool) => format!("({} != 0)", e),
            (Ty::Float, Ty::Bool) => format!("({} != 0)", e),
            _ => e,
        }
    }
}

/// Convert an int64/float64 expression to a member's storage type. Constant
/// expressions go through pbVal so that Go does not reject overflowing
/// constant conversions at compile time.
fn store_value(expr: &TExpr, code: String, ty: &ValueType) -> String {
    let mut deps = Vec::new();
    expr.deps(&mut deps);
    let code = if deps.is_empty() { format!("pbVal({})", code) } else { code };
    match ty {
        ValueType::Int { width, signed } => {
            let st = scalar_type(ty);
            if *width == crate::ir::storage_for(*width) {
                format!("{}({})", st, code)
            } else {
                format!("{}(pbTrunc({}, {}, {}))", st, code, width, signed)
            }
        }
        _ => format!("{}({})", scalar_type(ty), code),
    }
}

fn read_elem(codec: &Codec, ty: &ValueType) -> String {
    let st = scalar_type(ty);
    let raw = match codec {
        Codec::Bytes { nbytes, endian } => format!("pbR.ReadUint({}, {})", nbytes, little(endian)),
        Codec::Bits { width } => format!("pbR.ReadBits({})", width),
        Codec::Float { width: 32, endian } => {
            return format!("math.Float32frombits(uint32(pbR.ReadUint(4, {})))", little(endian));
        }
        Codec::Float { endian, .. } => return format!("math.Float64frombits(pbR.ReadUint(8, {}))", little(endian)),
        Codec::Mac => return "pbR.ReadMac()".into(),
        Codec::Packet(n) => return format!("pbDecode{}(pbR)", n),
        Codec::Str(_) => unreachable!("strings are handled separately"),
    };
    match ty {
        ValueType::Int { width, signed: true } => format!("{}(pbSext({}, {}))", st, raw, width),
        _ => format!("{}({})", st, raw),
    }
}

fn write_elem(out: &mut Out, codec: &Codec, ty: &ValueType, v: &str, field: &str) {
    if let ValueType::Int { width, signed } = ty
        && ty.needs_range_check()
    {
        if *signed {
            out.line(format!("pbW.CheckI(int64({}), {}, \"{}\")", v, width, field));
        } else {
            out.line(format!("pbW.CheckU(uint64({}), {}, \"{}\")", v, width, field));
        }
    }
    match codec {
        Codec::Bytes { nbytes, endian } => {
            out.line(format!("pbW.WriteUint(uint64({}), {}, {})", v, nbytes, little(endian)))
        }
        Codec::Bits { width } => out.line(format!("pbW.WriteBits(uint64({}), {})", v, width)),
        Codec::Float { width: 32, endian } => {
            out.line(format!("pbW.WriteUint(uint64(math.Float32bits({})), 4, {})", v, little(endian)))
        }
        Codec::Float { endian, .. } => {
            out.line(format!("pbW.WriteUint(math.Float64bits({}), 8, {})", v, little(endian)))
        }
        Codec::Mac => out.line(format!("pbW.WriteBytes({}[:])", v)),
        Codec::Packet(_) => out.line(format!("{}.EncodeTo(pbW)", v)),
        Codec::Str(_) => unreachable!("strings are handled separately"),
    }
}

fn emit_packet(out: &mut Out, p: &Packet) {
    let name = &p.name;
    out.open(format!("type {} struct {{", name));
    // gofmt alignment
    let width = p.members.iter().map(|m| field_name(&m.name).len()).max().unwrap_or(0);
    for m in &p.members {
        out.line(format!("{:<w$} {}", field_name(&m.name), member_type(m), w = width));
    }
    out.close("}");
    out.line("");

    out.line(format!("// Decode{} decodes a {} from the start of data. Trailing bytes are ignored.", name, name));
    out.open(format!("func Decode{}(data []byte) (*{}, error) {{", name, name));
    out.line("pbR := NewPbReader(data)");
    out.line(format!("p := pbDecode{}(pbR)", name));
    out.open("if err := pbR.Err(); err != nil {");
    out.line("return nil, err");
    out.close("}");
    out.line("return &p, nil");
    out.close("}");
    out.line("");

    out.line(format!("// DecodeFrom reads a {} from pbR, which keeps its position.", name));
    out.open(format!("func (p *{}) DecodeFrom(pbR *PbReader) error {{", name));
    out.line(format!("*p = pbDecode{}(pbR)", name));
    out.line("return pbR.Err()");
    out.close("}");
    out.line("");

    out.open(format!("func pbDecode{}(pbR *PbReader) (p {}) {{", name, name));
    if p.uses_align() {
        out.line("pbStart := pbR.PositionBits()");
    }
    let lang = Lang { packet: p, mode: Mode::Decode };
    for step in &p.steps {
        emit_decode_step(out, p, &lang, step);
    }
    out.line("return p");
    out.close("}");
    out.line("");

    out.open(format!("func (p *{}) Encode() ([]byte, error) {{", name));
    out.line("pbW := NewPbWriter()");
    out.open("if err := p.EncodeTo(pbW); err != nil {");
    out.line("return nil, err");
    out.close("}");
    out.line("return pbW.Bytes(), nil");
    out.close("}");
    out.line("");

    out.open(format!("func (p *{}) EncodeTo(pbW *PbWriter) error {{", name));
    if p.uses_align() {
        out.line("pbStart := pbW.PositionBits()");
    }
    let lang = Lang { packet: p, mode: Mode::Encode };
    for &c in &p.encode_calcs {
        let m = &p.members[c];
        if let MemberKind::Calculated(e) = &m.kind {
            out.line(format!("pbc_{} := {}", m.name, store_value(e, emit_expr(&lang, e), &m.ty)));
        }
    }
    for step in &p.steps {
        emit_encode_step(out, p, &lang, step);
    }
    out.line("return pbW.Err()");
    out.close("}");
}

fn emit_decode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Align { bytes } => out.line(format!("pbR.SkipBits(pbPad(pbR.PositionBits()-pbStart, {}))", bytes * 8)),
        Step::Field { member: Some(mi), codec: Codec::Str(mode), array, .. } => {
            let m = &p.members[*mi];
            let raw = match (mode, array) {
                (StrMode::CString, _) => format!("pbR.ReadCString(\"{}\")", m.name),
                (StrMode::Prefixed { prefix, .. }, _) => format!(
                    "pbR.ReadBytes(pbR.Count(int64({}), 8, \"{}\"))",
                    read_elem(prefix, &ValueType::Int { width: 64, signed: false }),
                    m.name
                ),
                (_, Some(Count::Expr(e))) => {
                    format!("pbR.ReadBytes(pbR.Count({}, 8, \"{}\"))", emit_expr(lang, e), m.name)
                }
                _ => "pbR.ReadBytes(pbR.RemainingBits()/8)".to_string(),
            };
            out.line(format!(
                "p.{} = pbR.Text({}, {}, \"{}\")",
                field_name(&m.name),
                raw,
                *mode == StrMode::Padded,
                m.name
            ));
        }
        Step::Calc { member } => {
            let m = &p.members[*member];
            if let MemberKind::Calculated(e) = &m.kind {
                out.line(format!("p.{} = {}", field_name(&m.name), store_value(e, emit_expr(lang, e), &m.ty)));
            }
        }
        Step::Field { member: None, codec, array, .. } => {
            let bits = codec.bits();
            match array {
                None => out.line(format!("pbR.SkipBits({})", bits)),
                Some(Count::Expr(e)) => {
                    out.line(format!("pbR.SkipBits(pbR.Count({}, {}, \"_\") * {})", emit_expr(lang, e), bits, bits))
                }
                Some(Count::Remaining) => out.line("pbR.SkipBits(pbR.RemainingBits())"),
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let target = format!("p.{}", field_name(&m.name));
            let ebits = codec.min_elem_bits();
            match array {
                None => out.line(format!("{} = {}", target, read_elem(codec, ty))),
                Some(Count::Expr(e)) => {
                    let n = format!("pbR.Count({}, {}, \"{}\")", emit_expr(lang, e), ebits, m.name);
                    if ty.is_byte() {
                        out.line(format!("{} = pbR.ReadBytes({})", target, n));
                    } else {
                        out.open("{");
                        out.line(format!("pbN := {}", n));
                        out.line(format!("{} = make({}, 0, pbN)", target, member_type(m)));
                        out.open("for pbI := 0; pbI < pbN && pbR.Err() == nil; pbI++ {");
                        out.line(format!("{} = append({}, {})", target, target, read_elem(codec, ty)));
                        out.close("}");
                        out.close("}");
                    }
                }
                Some(Count::Remaining) => {
                    if ty.is_byte() {
                        out.line(format!("{} = pbR.ReadBytes(pbR.RemainingBits() / 8)", target));
                    } else {
                        out.line(format!("{} = {}{{}}", target, member_type(m)));
                        out.open("for pbR.Err() == nil && pbR.RemainingBits() > 0 {");
                        out.line(format!("{} = append({}, {})", target, target, read_elem(codec, ty)));
                        out.close("}");
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            out.open("{");
            let raw = match container {
                Codec::Bytes { nbytes, endian } => format!("pbR.ReadUint({}, {})", nbytes, little(endian)),
                _ => format!("pbR.ReadBits({})", container_width),
            };
            out.line(format!("pbC := {}", raw));
            out.line("_ = pbC");
            for part in parts {
                let m = &p.members[part.member];
                let st = scalar_type(&m.ty);
                let bits = format!("((pbC >> {}) & 0x{:x})", part.shift, mask(part.width));
                let v = if part.signed {
                    format!("{}(pbSext({}, {}))", st, bits, part.width)
                } else {
                    format!("{}({})", st, bits)
                };
                out.line(format!("p.{} = {}", field_name(&m.name), v));
            }
            out.close("}");
        }
    }
}

fn emit_encode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Align { bytes } => {
            out.line(format!("pbW.WriteZeroBits(int64(pbPad(pbW.PositionBits()-pbStart, {})))", bytes * 8))
        }
        Step::Field { member: Some(mi), codec: Codec::Str(mode), array, .. } => {
            let m = &p.members[*mi];
            out.open("{");
            out.line(format!("pbW.CheckUTF8(p.{}, \"{}\")", field_name(&m.name), m.name));
            out.line(format!("pbB := []byte(p.{})", field_name(&m.name)));
            match (mode, array) {
                (StrMode::CString, _) => {
                    out.line(format!("pbW.CheckNoNul(pbB, \"{}\")", m.name));
                    out.line("pbW.WriteBytes(pbB)");
                    out.line("pbW.WriteBytes([]byte{0})");
                }
                (StrMode::Prefixed { prefix, width }, _) => {
                    out.line(format!("pbW.CheckU(uint64(len(pbB)), {}, \"{}\")", width, m.name));
                    write_elem(out, prefix, &ValueType::Int { width: 64, signed: false }, "len(pbB)", &m.name);
                    out.line("pbW.WriteBytes(pbB)");
                }
                (StrMode::Padded, Some(Count::Expr(e))) => {
                    out.line(format!("pbN := {}", emit_expr(lang, e)));
                    out.line(format!("pbW.CheckFits(len(pbB), pbN, \"{}\")", m.name));
                    out.line("pbW.WriteBytes(pbB)");
                    out.line("pbW.WriteZeroBits((pbN - int64(len(pbB))) * 8)");
                }
                (_, Some(Count::Expr(e))) => {
                    out.line(format!("pbW.CheckLen(len(pbB), {}, \"{}\")", emit_expr(lang, e), m.name));
                    out.line("pbW.WriteBytes(pbB)");
                }
                _ => out.line("pbW.WriteBytes(pbB)"),
            }
            out.close("}");
        }
        Step::Calc { .. } => {}
        Step::Field { member: None, codec, array, .. } => {
            let bits = codec.bits();
            match array {
                None => out.line(format!("pbW.WriteZeroBits({})", bits)),
                Some(Count::Expr(e)) => {
                    out.line(format!("pbW.WriteZeroBits(pbMax({}, 0) * {})", emit_expr(lang, e), bits))
                }
                Some(Count::Remaining) => {}
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let place = format!("p.{}", field_name(&m.name));
            match array {
                None => write_elem(out, codec, ty, &place, &m.name),
                Some(count) => {
                    if let Count::Expr(e) = count {
                        out.line(format!("pbW.CheckLen(len({}), {}, \"{}\")", place, emit_expr(lang, e), m.name));
                    }
                    if ty.is_byte() {
                        out.line(format!("pbW.WriteBytes({})", place));
                    } else {
                        out.open(format!("for pbI := range {} {{", place));
                        write_elem(out, codec, ty, &format!("{}[pbI]", place), &m.name);
                        out.close("}");
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            out.open("{");
            out.line("var pbC uint64");
            for part in parts {
                let m = &p.members[part.member];
                let place = format!("p.{}", field_name(&m.name));
                if part.signed {
                    out.line(format!("pbW.CheckI(int64({}), {}, \"{}\")", place, part.width, m.name));
                } else {
                    out.line(format!("pbW.CheckU(uint64({}), {}, \"{}\")", place, part.width, m.name));
                }
                out.line(format!("pbC |= (uint64({}) & 0x{:x}) << {}", place, mask(part.width), part.shift));
            }
            match container {
                Codec::Bytes { nbytes, endian } => {
                    out.line(format!("pbW.WriteUint(pbC, {}, {})", nbytes, little(endian)))
                }
                _ => out.line(format!("pbW.WriteBits(pbC, {})", container_width)),
            }
            out.close("}");
        }
    }
}
