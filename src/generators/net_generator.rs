//! C# backend: one file, no dependencies beyond the base class library.

use crate::generators::common::{ExprLang, GenOptions, Mode, Out, emit_expr, is_calc, mask, pascal_case};
use crate::ir::{AggOp, ArithOp, Codec, Count, Func, Member, MemberKind, Module, Packet, Step, Ty, ValueType};
use crate::models::parsing_models::Endianness;

pub struct CSharpGenerator;

const RUNTIME: &str = include_str!("../../runtime/csharp.cs");

/// C# property name for a member of packet `packet`.
pub fn prop_name(packet: &str, name: &str) -> String {
    let n = pascal_case(name);
    match n.as_str() {
        "Decode" | "DecodeFrom" | "Encode" | "EncodeTo" | "GetType" | "ToString" | "Equals" | "GetHashCode" => {
            format!("{}_", n)
        }
        _ if n == packet => format!("{}_", n),
        _ => n,
    }
}

pub fn namespace(opts: &GenOptions) -> String {
    pascal_case(&opts.package)
}

pub fn scalar_type(ty: &ValueType) -> String {
    match ty {
        ValueType::Int { width, signed } => match (crate::ir::storage_for(*width), signed) {
            (8, false) => "byte",
            (8, true) => "sbyte",
            (16, false) => "ushort",
            (16, true) => "short",
            (32, false) => "uint",
            (32, true) => "int",
            (_, false) => "ulong",
            (_, true) => "long",
        }
        .to_string(),
        ValueType::Float { width: 32 } => "float".into(),
        ValueType::Float { .. } => "double".into(),
        ValueType::Mac => "byte[]".into(),
        ValueType::Packet(n) => n.clone(),
    }
}

pub fn member_type(m: &Member) -> String {
    match m.array {
        Some(_) => format!("{}[]", scalar_type(&m.ty)),
        None => scalar_type(&m.ty),
    }
}

impl CSharpGenerator {
    pub fn generate(module: &Module, opts: &GenOptions) -> String {
        let mut out = Out::new("    ");
        out.line("// <auto-generated> Generated by packet-builder. Do not edit. </auto-generated>");
        out.line("using System;");
        out.line("using System.Collections.Generic;");
        out.line("using System.Linq;");
        out.line("");
        out.line(format!("namespace {}", namespace(opts)));
        out.open("{");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            emit_packet(&mut out, p);
        }
        out.close("}");
        out.buf
    }
}

fn little(e: &Endianness) -> &'static str {
    if *e == Endianness::Le { "true" } else { "false" }
}

struct Lang<'a> {
    packet: &'a Packet,
    mode: Mode,
}

impl<'a> Lang<'a> {
    fn place(&self, member: usize) -> String {
        let m = &self.packet.members[member];
        if self.mode == Mode::Encode && is_calc(m) {
            format!("pbc_{}", m.name)
        } else {
            format!("p.{}", prop_name(&self.packet.name, &m.name))
        }
    }
}

impl<'a> ExprLang for Lang<'a> {
    fn int_lit(&self, v: i64) -> String {
        format!("({}L)", v)
    }

    fn float_lit(&self, v: f64) -> String {
        format!("({:?}d)", v)
    }

    fn member_ref(&self, member: usize, ty: Ty) -> String {
        let t = if ty == Ty::Float { "double" } else { "long" };
        format!("(({}){})", t, self.place(member))
    }

    fn index(&self, member: usize, index: String, ty: Ty) -> String {
        let t = if ty == Ty::Float { "double" } else { "long" };
        format!("(({})Pb.At({}, {}))", t, self.place(member), index)
    }

    fn aggregate(&self, member: usize, op: AggOp, ty: Ty) -> String {
        let place = self.place(member);
        match (op, ty) {
            (AggOp::Sum, Ty::Float) => format!("{}.Aggregate(0.0d, (pbA, pbV) => pbA + (double)pbV)", place),
            (AggOp::Product, Ty::Float) => format!("{}.Aggregate(1.0d, (pbA, pbV) => pbA * (double)pbV)", place),
            (AggOp::Sum, _) => format!("{}.Aggregate(0L, (pbA, pbV) => unchecked(pbA + (long)pbV))", place),
            (AggOp::Product, _) => format!("{}.Aggregate(1L, (pbA, pbV) => unchecked(pbA * (long)pbV))", place),
        }
    }

    fn arith(&self, op: ArithOp, a: String, b: String, ty: Ty) -> String {
        match (op, ty) {
            (ArithOp::Add, _) => format!("({} + {})", a, b),
            (ArithOp::Sub, _) => format!("({} - {})", a, b),
            (ArithOp::Mul, _) => format!("({} * {})", a, b),
            (ArithOp::Div, Ty::Float) => format!("({} / {})", a, b),
            (ArithOp::Div, _) => format!("Pb.Div({}, {})", a, b),
            (ArithOp::Pow, Ty::Float) => format!("Math.Pow({}, {})", a, b),
            (ArithOp::Pow, _) => format!("Pb.Pow({}, {})", a, b),
        }
    }

    fn guard(&self, cond: String, then: String, other: String, _ty: Ty) -> String {
        format!("({} ? {} : {})", cond, then, other)
    }

    fn call(&self, func: Func, args: Vec<String>, _ty: Ty) -> String {
        match func {
            Func::Sqrt => format!("Math.Sqrt({})", args[0]),
            Func::Min => format!("Math.Min({}, {})", args[0], args[1]),
            Func::Max => format!("Math.Max({}, {})", args[0], args[1]),
        }
    }

    fn convert(&self, e: String, from: Ty, to: Ty) -> String {
        match (from, to) {
            (Ty::Bool, Ty::Int) => format!("({} ? 1L : 0L)", e),
            (Ty::Bool, Ty::Float) => format!("({} ? 1.0d : 0.0d)", e),
            (Ty::Int, Ty::Float) => format!("((double)({}))", e),
            (Ty::Float, Ty::Int) => format!("Pb.FtoI({})", e),
            (Ty::Int, Ty::Bool) => format!("({} != 0L)", e),
            (Ty::Float, Ty::Bool) => format!("({} != 0.0d)", e),
            _ => e,
        }
    }
}

/// Convert a long/double expression to a member's storage type. `unchecked`
/// gives wrapping semantics even for constant expressions.
fn store_value(expr: String, ty: &ValueType) -> String {
    match ty {
        ValueType::Int { width, signed } => {
            let st = scalar_type(ty);
            if *width == crate::ir::storage_for(*width) {
                format!("unchecked(({})({}))", st, expr)
            } else {
                format!("unchecked(({})Pb.Trunc({}, {}, {}))", st, expr, width, signed)
            }
        }
        _ => format!("unchecked(({})({}))", scalar_type(ty), expr),
    }
}

fn read_elem(codec: &Codec, ty: &ValueType) -> String {
    let st = scalar_type(ty);
    let raw = match codec {
        Codec::Bytes { nbytes, endian } => format!("pbR.ReadUint({}, {})", nbytes, little(endian)),
        Codec::Bits { width } => format!("pbR.ReadBits({})", width),
        Codec::Float { width: 32, endian } => {
            return format!("BitConverter.Int32BitsToSingle(unchecked((int)pbR.ReadUint(4, {})))", little(endian));
        }
        Codec::Float { endian, .. } => {
            return format!("BitConverter.Int64BitsToDouble(unchecked((long)pbR.ReadUint(8, {})))", little(endian));
        }
        Codec::Mac => return "pbR.ReadBytes(6)".into(),
        Codec::Packet(n) => return format!("{}.DecodeFrom(pbR)", n),
    };
    match ty {
        ValueType::Int { width, signed: true } => format!("unchecked(({})Pb.Sext({}, {}))", st, raw, width),
        _ => format!("unchecked(({}){})", st, raw),
    }
}

fn write_elem(out: &mut Out, codec: &Codec, ty: &ValueType, v: &str, field: &str) {
    match ty {
        ValueType::Int { width, signed } if ty.needs_range_check() => {
            if *signed {
                out.line(format!("Pb.CheckI((long){}, {}, \"{}\");", v, width, field));
            } else {
                out.line(format!("Pb.CheckU((ulong){}, {}, \"{}\");", v, width, field));
            }
        }
        ValueType::Mac => out.line(format!("Pb.CheckLen({}.Length, 6, \"{}\");", v, field)),
        _ => {}
    }
    match codec {
        Codec::Bytes { nbytes, endian } => {
            out.line(format!("pbW.WriteUint(unchecked((ulong){}), {}, {});", v, nbytes, little(endian)))
        }
        Codec::Bits { width } => out.line(format!("pbW.WriteBits(unchecked((ulong){}), {});", v, width)),
        Codec::Float { width: 32, endian } => out.line(format!(
            "pbW.WriteUint(unchecked((uint)BitConverter.SingleToInt32Bits({})), 4, {});",
            v,
            little(endian)
        )),
        Codec::Float { endian, .. } => out.line(format!(
            "pbW.WriteUint(unchecked((ulong)BitConverter.DoubleToInt64Bits({})), 8, {});",
            v,
            little(endian)
        )),
        Codec::Mac => out.line(format!("pbW.WriteBytes({});", v)),
        Codec::Packet(_) => out.line(format!("{}.EncodeTo(pbW);", v)),
    }
}

fn default_value(m: &Member) -> Option<String> {
    match (&m.array, &m.ty) {
        (Some(_), ty) => Some(format!("Array.Empty<{}>()", scalar_type(ty))),
        (None, ValueType::Mac) => Some("new byte[6]".into()),
        (None, ValueType::Packet(n)) => Some(format!("new {}()", n)),
        _ => None,
    }
}

fn emit_packet(out: &mut Out, p: &Packet) {
    let name = &p.name;
    out.line(format!("public sealed class {}", name));
    out.open("{");
    for m in &p.members {
        let decl = format!("public {} {} {{ get; set; }}", member_type(m), prop_name(name, &m.name));
        match default_value(m) {
            Some(d) => out.line(format!("{} = {};", decl, d)),
            None => out.line(decl),
        }
    }
    out.line("");
    out.line("/// <summary>Decode from the start of <paramref name=\"data\"/>. Trailing bytes are ignored.</summary>");
    out.line(format!("public static {} Decode(byte[] data) => DecodeFrom(new PbReader(data));", name));
    out.line("");
    out.line(format!("public static {} DecodeFrom(PbReader pbR)", name));
    out.open("{");
    out.line(format!("var p = new {}();", name));
    let lang = Lang { packet: p, mode: Mode::Decode };
    for step in &p.steps {
        emit_decode_step(out, p, &lang, step);
    }
    out.line("return p;");
    out.close("}");
    out.line("");
    out.line("public byte[] Encode()");
    out.open("{");
    out.line("var pbW = new PbWriter();");
    out.line("EncodeTo(pbW);");
    out.line("return pbW.ToArray();");
    out.close("}");
    out.line("");
    out.line("public void EncodeTo(PbWriter pbW)");
    out.open("{");
    out.line("var p = this;");
    let lang = Lang { packet: p, mode: Mode::Encode };
    for &c in &p.encode_calcs {
        let m = &p.members[c];
        if let MemberKind::Calculated(e) = &m.kind {
            out.line(format!("{} pbc_{} = {};", scalar_type(&m.ty), m.name, store_value(emit_expr(&lang, e), &m.ty)));
        }
    }
    for step in &p.steps {
        emit_encode_step(out, p, &lang, step);
    }
    out.close("}");
    out.close("}");
}

fn emit_decode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Calc { member } => {
            let m = &p.members[*member];
            if let MemberKind::Calculated(e) = &m.kind {
                out.line(format!("p.{} = {};", prop_name(&p.name, &m.name), store_value(emit_expr(lang, e), &m.ty)));
            }
        }
        Step::Field { member: None, codec, array, .. } => {
            let bits = codec.bits();
            match array {
                None => out.line(format!("pbR.SkipBits({});", bits)),
                Some(Count::Expr(e)) => out.line(format!(
                    "pbR.SkipBits((long)pbR.Count({}, {}, \"_\") * {});",
                    emit_expr(lang, e),
                    bits,
                    bits
                )),
                Some(Count::Remaining) => out.line("pbR.SkipBits(pbR.RemainingBits);"),
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let target = format!("p.{}", prop_name(&p.name, &m.name));
            let ebits = codec.min_elem_bits();
            match array {
                None => out.line(format!("{} = {};", target, read_elem(codec, ty))),
                Some(Count::Expr(e)) => {
                    let n = format!("pbR.Count({}, {}, \"{}\")", emit_expr(lang, e), ebits, m.name);
                    if ty.is_byte() {
                        out.line(format!("{} = pbR.ReadBytes({});", target, n));
                    } else {
                        out.open("{");
                        out.line(format!("int pbN = {};", n));
                        out.line(format!("var pbA = new {}[pbN];", scalar_type(ty)));
                        out.line(format!("for (int pbI = 0; pbI < pbN; pbI++) pbA[pbI] = {};", read_elem(codec, ty)));
                        out.line(format!("{} = pbA;", target));
                        out.close("}");
                    }
                }
                Some(Count::Remaining) => {
                    if ty.is_byte() {
                        out.line(format!("{} = pbR.ReadBytes(pbR.RemainingBits / 8);", target));
                    } else {
                        out.open("{");
                        out.line(format!("var pbL = new List<{}>();", scalar_type(ty)));
                        out.line(format!("while (pbR.RemainingBits > 0) pbL.Add({});", read_elem(codec, ty)));
                        out.line(format!("{} = pbL.ToArray();", target));
                        out.close("}");
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            out.open("{");
            let raw = match container {
                Codec::Bytes { nbytes, endian } => format!("pbR.ReadUint({}, {})", nbytes, little(endian)),
                _ => format!("pbR.ReadBits({})", container_width),
            };
            out.line(format!("ulong pbC = {};", raw));
            for part in parts {
                let m = &p.members[part.member];
                let st = scalar_type(&m.ty);
                let bits = format!("((pbC >> {}) & 0x{:x}UL)", part.shift, mask(part.width));
                let v = if part.signed {
                    format!("unchecked(({})Pb.Sext({}, {}))", st, bits, part.width)
                } else {
                    format!("unchecked(({}){})", st, bits)
                };
                out.line(format!("p.{} = {};", prop_name(&p.name, &m.name), v));
            }
            out.close("}");
        }
    }
}

fn emit_encode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Calc { .. } => {}
        Step::Field { member: None, codec, array, .. } => {
            let bits = codec.bits();
            match array {
                None => out.line(format!("pbW.WriteZeroBits({});", bits)),
                Some(Count::Expr(e)) => {
                    out.line(format!("pbW.WriteZeroBits(Math.Max({}, 0L) * {});", emit_expr(lang, e), bits))
                }
                Some(Count::Remaining) => {}
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let place = format!("p.{}", prop_name(&p.name, &m.name));
            match array {
                None => write_elem(out, codec, ty, &place, &m.name),
                Some(count) => {
                    if let Count::Expr(e) = count {
                        out.line(format!("Pb.CheckLen({}.Length, {}, \"{}\");", place, emit_expr(lang, e), m.name));
                    }
                    if ty.is_byte() {
                        out.line(format!("pbW.WriteBytes({});", place));
                    } else {
                        out.line(format!("foreach (var pbV in {})", place));
                        out.open("{");
                        write_elem(out, codec, ty, "pbV", &m.name);
                        out.close("}");
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            out.open("{");
            out.line("ulong pbC = 0;");
            for part in parts {
                let m = &p.members[part.member];
                let place = format!("p.{}", prop_name(&p.name, &m.name));
                if part.signed {
                    out.line(format!("Pb.CheckI((long){}, {}, \"{}\");", place, part.width, m.name));
                } else {
                    out.line(format!("Pb.CheckU((ulong){}, {}, \"{}\");", place, part.width, m.name));
                }
                out.line(format!(
                    "pbC |= (unchecked((ulong){}) & 0x{:x}UL) << {};",
                    place,
                    mask(part.width),
                    part.shift
                ));
            }
            match container {
                Codec::Bytes { nbytes, endian } => {
                    out.line(format!("pbW.WriteUint(pbC, {}, {});", nbytes, little(endian)))
                }
                _ => out.line(format!("pbW.WriteBits(pbC, {});", container_width)),
            }
            out.close("}");
        }
    }
}
