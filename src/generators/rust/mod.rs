//! Rust backend: one self-contained module, no external crates.

mod decode;
mod encode;
mod expr;
mod naming;
mod packet;

pub use naming::{ident, member_type, scalar_type};

use crate::generators::Backend;
use crate::generators::common::{GenOptions, Out};
use crate::ir::Module;

pub struct RustGenerator;

const RUNTIME: &str = include_str!("../../../runtime/rust.rs");

impl Backend for RustGenerator {
    fn generate(&self, module: &Module, _opts: &GenOptions) -> String {
        let mut out = Out::new("    ");
        out.line("// Generated by packet-builder. Do not edit.");
        out.line("#![allow(dead_code, unused_variables, unused_mut, unused_parens, non_snake_case, non_camel_case_types, clippy::all)]");
        out.line("");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, p);
        }
        out.buf
    }
}
