//! Rust backend: one self-contained module, no external crates.

mod category;
mod decode;
mod encode;
mod expr;
mod json;
mod naming;
mod packet;
mod stream;

pub use naming::{ident, member_type, scalar_type};

use crate::generators::Backend;
use crate::generators::common::consts::with_versions;
use crate::generators::common::{ConstEmitter, GenOptions, Out};
use crate::ir::{Category, Constant, Module};

pub struct RustGenerator;

const RUNTIME: &str = include_str!("../../../runtime/rust.rs");

impl Backend for RustGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let types = naming::Types::new(module, opts.zero_copy);
        let mut out = Out::new("    ");
        out.line("// Generated by packet-builder. Do not edit.");
        out.line("#![allow(dead_code, unused_variables, unused_mut, unused_parens, non_snake_case, non_camel_case_types, non_upper_case_globals, clippy::all)]");
        if opts.zero_copy {
            out.line("");
            out.line("// Zero-copy: byte buffers and strings borrow the decoded input where they can.");
            out.line("use std::borrow::Cow;");
        }
        out.line("");
        out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME, module.has_versions()));
        self.emit_constants(&mut out, module);
        for u in &module.unions {
            packet::emit_union(&mut out, u, &types);
            json::emit_union_json(&mut out, u, types.generics(&u.name));
        }
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, module, p, &types);
        }
        out.buf
    }
}

/// `pub const NAME: u8 = 1;`, with the note as a doc comment.
fn const_line(out: &mut Out, c: &Constant) {
    if let Some(note) = &c.note {
        out.line(format!("/// {}", note));
    }
    out.line(format!("pub const {}: {} = {};", c.name.to_ascii_uppercase(), scalar_type(&c.ty), c.literal()));
}

impl ConstEmitter for RustGenerator {
    fn constant(&self, out: &mut Out, c: &Constant) {
        const_line(out, c);
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        category::emit(out, cat, &[]);
    }

    /// As the default, but a named range's enum also converts to and from its
    /// parent's, so each category sees the others.
    fn emit_constants(&self, out: &mut Out, module: &Module) {
        if !module.constants.is_empty() {
            self.separator(out);
            self.constants(out, &with_versions(&module.constants));
        }
        let all: Vec<Category> = module
            .categories
            .iter()
            .map(|cat| Category { members: with_versions(&cat.members), ..cat.clone() })
            .collect();
        for cat in &all {
            self.separator(out);
            category::emit(out, cat, &all);
        }
    }
}
