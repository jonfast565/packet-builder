//! Python backend: a single module using only the standard library.

use crate::generators::common::{ExprLang, GenOptions, Mode, Out, emit_expr, is_calc, mask};
use crate::ir::{
    AggOp, ArithOp, Codec, Count, Func, LogicOp, Member, MemberKind, Module, Packet, Step, StrMode, Ty, ValueType,
};
use crate::models::parsing_models::Endianness;

pub struct PythonGenerator;

const RUNTIME: &str = include_str!("../../runtime/python.py");

const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del",
    "elif", "else", "except", "finally", "for", "from", "global", "if", "import", "in", "is", "lambda", "nonlocal",
    "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
];

pub fn ident(name: &str) -> String {
    if KEYWORDS.contains(&name) { format!("{}_", name) } else { name.to_string() }
}

impl PythonGenerator {
    pub fn generate(module: &Module, _opts: &GenOptions) -> String {
        let mut out = Out::new("    ");
        out.line("# Generated by packet-builder. Do not edit.");
        out.line("from __future__ import annotations");
        out.line("");
        out.line("import math");
        out.line("import struct");
        out.line("from dataclasses import dataclass, field");
        out.line("from typing import List");
        out.line("");
        out.line("");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            out.line("");
            emit_packet(&mut out, p);
        }
        out.buf
    }
}

fn little(e: &Endianness) -> &'static str {
    if *e == Endianness::Le { "True" } else { "False" }
}

struct Lang<'a> {
    packet: &'a Packet,
    mode: Mode,
}

impl<'a> Lang<'a> {
    fn place(&self, member: usize) -> String {
        let m = &self.packet.members[member];
        if self.mode == Mode::Encode && is_calc(m) {
            format!("pbc_{}", m.name)
        } else {
            format!("p.{}", ident(&m.name))
        }
    }
}

/// u64 values must wrap to i64 to match the other languages.
fn needs_wrap(ty: &ValueType) -> bool {
    matches!(ty, ValueType::Int { width: 64, signed: false })
}

impl<'a> ExprLang for Lang<'a> {
    fn int_lit(&self, v: i64) -> String {
        if v < 0 { format!("({})", v) } else { v.to_string() }
    }

    fn float_lit(&self, v: f64) -> String {
        format!("{:?}", v)
    }

    fn member_ref(&self, member: usize, ty: Ty) -> String {
        let place = self.place(member);
        match ty {
            Ty::Float => format!("float({})", place),
            _ if needs_wrap(&self.packet.members[member].ty) => format!("_pb_wrap({})", place),
            _ => place,
        }
    }

    fn index(&self, member: usize, index: String, ty: Ty) -> String {
        let v = format!("_pb_at({}, {})", self.place(member), index);
        match ty {
            Ty::Float => format!("float({})", v),
            _ if needs_wrap(&self.packet.members[member].ty) => format!("_pb_wrap({})", v),
            _ => v,
        }
    }

    fn aggregate(&self, member: usize, op: AggOp, ty: Ty) -> String {
        let place = self.place(member);
        match (op, ty) {
            (AggOp::Sum, Ty::Float) => format!("math.fsum(float(v) for v in {})", place),
            (AggOp::Product, Ty::Float) => format!("math.prod(float(v) for v in {})", place),
            (AggOp::Sum, _) => format!("_pb_wrap(sum({}))", place),
            (AggOp::Product, _) => format!("_pb_wrap(math.prod({}))", place),
        }
    }

    fn arith(&self, op: ArithOp, a: String, b: String, ty: Ty) -> String {
        if ty == Ty::Float {
            return match op {
                ArithOp::Add => format!("({} + {})", a, b),
                ArithOp::Sub => format!("({} - {})", a, b),
                ArithOp::Mul => format!("({} * {})", a, b),
                ArithOp::Div => format!("_pb_fdiv({}, {})", a, b),
                ArithOp::Pow => format!("_pb_fpow({}, {})", a, b),
            };
        }
        match op {
            ArithOp::Add => format!("_pb_wrap({} + {})", a, b),
            ArithOp::Sub => format!("_pb_wrap({} - {})", a, b),
            ArithOp::Mul => format!("_pb_wrap({} * {})", a, b),
            ArithOp::Div => format!("_pb_div({}, {})", a, b),
            ArithOp::Pow => format!("_pb_pow({}, {})", a, b),
        }
    }

    fn logic(&self, op: LogicOp, a: String, b: String) -> String {
        let sym = if op == LogicOp::And { "and" } else { "or" };
        format!("({} {} {})", a, sym, b)
    }

    fn guard(&self, cond: String, then: String, other: String, _ty: Ty) -> String {
        format!("({} if {} else {})", then, cond, other)
    }

    fn call(&self, func: Func, args: Vec<String>, _ty: Ty) -> String {
        match func {
            Func::Sqrt => format!("_pb_sqrt({})", args[0]),
            Func::Min => format!("min({}, {})", args[0], args[1]),
            Func::Max => format!("max({}, {})", args[0], args[1]),
        }
    }

    fn convert(&self, e: String, from: Ty, to: Ty) -> String {
        match (from, to) {
            (Ty::Bool, Ty::Int) => format!("int({})", e),
            (Ty::Bool, Ty::Float) | (Ty::Int, Ty::Float) => format!("float({})", e),
            (Ty::Float, Ty::Int) => format!("_pb_ftoi({})", e),
            (Ty::Int, Ty::Bool) => format!("({} != 0)", e),
            (Ty::Float, Ty::Bool) => format!("({} != 0.0)", e),
            _ => e,
        }
    }
}

fn store_value(expr: String, ty: &ValueType) -> String {
    match ty {
        ValueType::Int { width, signed } => {
            format!("_pb_trunc({}, {}, {})", expr, width, if *signed { "True" } else { "False" })
        }
        ValueType::Float { width: 32 } => format!("_pb_f32({})", expr),
        _ => expr,
    }
}

fn read_elem(codec: &Codec, ty: &ValueType) -> String {
    let raw = match codec {
        Codec::Bytes { nbytes, endian } => format!("pb_r.read_uint({}, {})", nbytes, little(endian)),
        Codec::Bits { width } => format!("pb_r.read_bits({})", width),
        Codec::Float { width, endian } => {
            let fmt = format!(
                "{}{}",
                if *endian == Endianness::Le { "<" } else { ">" },
                if *width == 32 { "f" } else { "d" }
            );
            return format!("struct.unpack(\"{}\", pb_r.read_bytes({}))[0]", fmt, width / 8);
        }
        Codec::Mac => return "pb_r.read_bytes(6)".into(),
        Codec::Packet(n) => return format!("{}.decode_from(pb_r)", n),
        Codec::Str(_) => unreachable!("strings are handled separately"),
    };
    match ty {
        ValueType::Int { width, signed: true } => format!("_pb_sext({}, {})", raw, width),
        _ => raw,
    }
}

fn write_elem(out: &mut Out, codec: &Codec, ty: &ValueType, v: &str, field: &str) {
    match ty {
        ValueType::Int { width, signed: true } => out.line(format!("_pb_check_i({}, {}, \"{}\")", v, width, field)),
        ValueType::Int { width, signed: false } => out.line(format!("_pb_check_u({}, {}, \"{}\")", v, width, field)),
        ValueType::Mac => out.line(format!("_pb_check_len(len({}), 6, \"{}\")", v, field)),
        _ => {}
    }
    match codec {
        Codec::Bytes { nbytes, endian } => out.line(format!("pb_w.write_uint({}, {}, {})", v, nbytes, little(endian))),
        Codec::Bits { width } => out.line(format!("pb_w.write_bits({}, {})", v, width)),
        Codec::Float { width, endian } => {
            let fmt = format!(
                "{}{}",
                if *endian == Endianness::Le { "<" } else { ">" },
                if *width == 32 { "f" } else { "d" }
            );
            out.line(format!("pb_w.write_bytes(struct.pack(\"{}\", {}))", fmt, v));
        }
        Codec::Mac => out.line(format!("pb_w.write_bytes(bytes({}))", v)),
        Codec::Packet(_) => out.line(format!("{}.encode_to(pb_w)", v)),
        Codec::Str(_) => unreachable!("strings are handled separately"),
    }
}

fn annotation(m: &Member) -> String {
    let scalar = match &m.ty {
        ValueType::Int { .. } => "int".to_string(),
        ValueType::Float { .. } => "float".to_string(),
        ValueType::Mac => "bytes".to_string(),
        ValueType::Packet(n) => n.clone(),
        ValueType::Str => "str".to_string(),
    };
    match &m.array {
        Some(_) if m.ty.is_byte() => "bytes = b\"\"".into(),
        Some(_) => format!("List[{}] = field(default_factory=list)", scalar),
        None => match &m.ty {
            ValueType::Int { .. } => "int = 0".into(),
            ValueType::Float { .. } => "float = 0.0".into(),
            ValueType::Mac => "bytes = bytes(6)".into(),
            ValueType::Packet(n) => format!("{} = field(default_factory=lambda: {}())", n, n),
            ValueType::Str => "str = \"\"".into(),
        },
    }
}

fn emit_packet(out: &mut Out, p: &Packet) {
    out.line("@dataclass");
    out.open(format!("class {}:", p.name));
    if p.members.is_empty() {
        out.line("pass");
    }
    for m in &p.members {
        out.line(format!("{}: {}", ident(&m.name), annotation(m)));
    }
    out.line("");
    out.line("@classmethod");
    out.open(format!("def decode(cls, data) -> \"{}\":", p.name));
    out.line("\"\"\"Decode from the start of `data`. Trailing bytes are ignored.\"\"\"");
    out.line("return cls.decode_from(PbReader(data))");
    out.close("");
    out.line("@classmethod");
    out.open(format!("def decode_from(cls, pb_r) -> \"{}\":", p.name));
    out.line("p = cls()");
    if p.uses_align() {
        out.line("pb_start = pb_r.position_bits()");
    }
    let lang = Lang { packet: p, mode: Mode::Decode };
    for step in &p.steps {
        emit_decode_step(out, p, &lang, step);
    }
    out.line("return p");
    out.close("");

    out.open("def encode(self) -> bytes:");
    out.line("pb_w = PbWriter()");
    out.line("self.encode_to(pb_w)");
    out.line("return pb_w.finish()");
    out.close("");
    out.open("def encode_to(self, pb_w) -> None:");
    out.line("p = self");
    if p.uses_align() {
        out.line("pb_start = pb_w.position_bits()");
    }
    let lang = Lang { packet: p, mode: Mode::Encode };
    for &c in &p.encode_calcs {
        let m = &p.members[c];
        if let MemberKind::Calculated(e) = &m.kind {
            out.line(format!("pbc_{} = {}", m.name, store_value(emit_expr(&lang, e), &m.ty)));
        }
    }
    for step in &p.steps {
        emit_encode_step(out, p, &lang, step);
    }
    out.close("");
    out.pop();
}

fn emit_decode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Align { bytes } => {
            out.line(format!("pb_r.skip_bits(_pb_pad(pb_r.position_bits() - pb_start, {}))", bytes * 8))
        }
        Step::Field { member: Some(mi), codec: Codec::Str(mode), array, .. } => {
            let m = &p.members[*mi];
            let raw = match (mode, array) {
                (StrMode::CString, _) => format!("pb_r.read_cstring(\"{}\")", m.name),
                (StrMode::Prefixed { prefix, .. }, _) => format!(
                    "pb_r.read_bytes(_pb_count({}, 8, pb_r, \"{}\"))",
                    read_elem(prefix, &ValueType::Int { width: 64, signed: false }),
                    m.name
                ),
                (_, Some(Count::Expr(e))) => {
                    format!("pb_r.read_bytes(_pb_count({}, 8, pb_r, \"{}\"))", emit_expr(lang, e), m.name)
                }
                _ => "pb_r.read_bytes(pb_r.remaining_bits() // 8)".to_string(),
            };
            let raw = if *mode == StrMode::Padded { format!("_pb_until_nul({})", raw) } else { raw };
            out.line(format!("p.{} = _pb_utf8({}, \"{}\")", ident(&m.name), raw, m.name));
        }
        Step::Calc { member } => {
            let m = &p.members[*member];
            if let MemberKind::Calculated(e) = &m.kind {
                out.line(format!("p.{} = {}", ident(&m.name), store_value(emit_expr(lang, e), &m.ty)));
            }
        }
        Step::Field { member: None, codec, array, .. } => {
            let bits = codec.bits();
            match array {
                None => out.line(format!("pb_r.skip_bits({})", bits)),
                Some(Count::Expr(e)) => out.line(format!(
                    "pb_r.skip_bits(_pb_count({}, {}, pb_r, \"_\") * {})",
                    emit_expr(lang, e),
                    bits,
                    bits
                )),
                Some(Count::Remaining) => out.line("pb_r.skip_bits(pb_r.remaining_bits())"),
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let target = format!("p.{}", ident(&m.name));
            let ebits = codec.min_elem_bits();
            match array {
                None => out.line(format!("{} = {}", target, read_elem(codec, ty))),
                Some(Count::Expr(e)) => {
                    let n = format!("_pb_count({}, {}, pb_r, \"{}\")", emit_expr(lang, e), ebits, m.name);
                    if ty.is_byte() {
                        out.line(format!("{} = pb_r.read_bytes({})", target, n));
                    } else {
                        out.line(format!("{} = [{} for _ in range({})]", target, read_elem(codec, ty), n));
                    }
                }
                Some(Count::Remaining) => {
                    if ty.is_byte() {
                        out.line(format!("{} = pb_r.read_bytes(pb_r.remaining_bits() // 8)", target));
                    } else {
                        out.line(format!("{} = []", target));
                        out.open("while pb_r.remaining_bits() > 0:");
                        out.line(format!("{}.append({})", target, read_elem(codec, ty)));
                        out.pop();
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            let raw = match container {
                Codec::Bytes { nbytes, endian } => format!("pb_r.read_uint({}, {})", nbytes, little(endian)),
                _ => format!("pb_r.read_bits({})", container_width),
            };
            out.line(format!("pb_c = {}", raw));
            for part in parts {
                let m = &p.members[part.member];
                let bits = format!("((pb_c >> {}) & 0x{:x})", part.shift, mask(part.width));
                let v = if part.signed { format!("_pb_sext({}, {})", bits, part.width) } else { bits };
                out.line(format!("p.{} = {}", ident(&m.name), v));
            }
        }
    }
}

fn emit_encode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Align { bytes } => {
            out.line(format!("pb_w.write_zero_bits(_pb_pad(pb_w.position_bits() - pb_start, {}))", bytes * 8))
        }
        Step::Field { member: Some(mi), codec: Codec::Str(mode), array, .. } => {
            let m = &p.members[*mi];
            out.line(format!("pb_b = _pb_utf8_bytes(p.{}, \"{}\")", ident(&m.name), m.name));
            match (mode, array) {
                (StrMode::CString, _) => {
                    out.line(format!("_pb_check_no_nul(pb_b, \"{}\")", m.name));
                    out.line("pb_w.write_bytes(pb_b + b\"\\0\")");
                }
                (StrMode::Prefixed { prefix, width }, _) => {
                    out.line(format!("_pb_check_u(len(pb_b), {}, \"{}\")", width, m.name));
                    write_elem(out, prefix, &ValueType::Int { width: 64, signed: false }, "len(pb_b)", &m.name);
                    out.line("pb_w.write_bytes(pb_b)");
                }
                (StrMode::Padded, Some(Count::Expr(e))) => {
                    out.line(format!("pb_n = {}", emit_expr(lang, e)));
                    out.line(format!("_pb_check_fits(len(pb_b), pb_n, \"{}\")", m.name));
                    out.line("pb_w.write_bytes(pb_b + bytes(pb_n - len(pb_b)))");
                }
                (_, Some(Count::Expr(e))) => {
                    out.line(format!("_pb_check_len(len(pb_b), {}, \"{}\")", emit_expr(lang, e), m.name));
                    out.line("pb_w.write_bytes(pb_b)");
                }
                _ => out.line("pb_w.write_bytes(pb_b)"),
            }
        }
        Step::Calc { .. } => {}
        Step::Field { member: None, codec, array, .. } => {
            let bits = codec.bits();
            match array {
                None => out.line(format!("pb_w.write_zero_bits({})", bits)),
                Some(Count::Expr(e)) => {
                    out.line(format!("pb_w.write_zero_bits(max({}, 0) * {})", emit_expr(lang, e), bits))
                }
                Some(Count::Remaining) => {}
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let place = format!("p.{}", ident(&m.name));
            match array {
                None => write_elem(out, codec, ty, &place, &m.name),
                Some(count) => {
                    if let Count::Expr(e) = count {
                        out.line(format!("_pb_check_len(len({}), {}, \"{}\")", place, emit_expr(lang, e), m.name));
                    }
                    if ty.is_byte() {
                        out.line(format!("pb_w.write_bytes(bytes({}))", place));
                    } else {
                        out.open(format!("for pb_v in {}:", place));
                        write_elem(out, codec, ty, "pb_v", &m.name);
                        out.pop();
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            out.line("pb_c = 0");
            for part in parts {
                let m = &p.members[part.member];
                let place = format!("p.{}", ident(&m.name));
                if part.signed {
                    out.line(format!("_pb_check_i({}, {}, \"{}\")", place, part.width, m.name));
                } else {
                    out.line(format!("_pb_check_u({}, {}, \"{}\")", place, part.width, m.name));
                }
                out.line(format!("pb_c |= ({} & 0x{:x}) << {}", place, mask(part.width), part.shift));
            }
            match container {
                Codec::Bytes { nbytes, endian } => {
                    out.line(format!("pb_w.write_uint(pb_c, {}, {})", nbytes, little(endian)))
                }
                _ => out.line(format!("pb_w.write_bits(pb_c, {})", container_width)),
            }
        }
    }
}
