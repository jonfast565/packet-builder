pub use naming::{ident, scalar_type};

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out};
use crate::ir::{Category, Constant, Module};

pub struct SwiftGenerator;

const RUNTIME: &str = include_str!("../../../runtime/swift.swift");

impl Backend for SwiftGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let types = naming::Types::new(module, opts.zero_copy);
        let mut out = Out::new("    ");
        out.line("// Generated by packet-builder. Do not edit.");
        if opts.zero_copy {
            out.line("// Zero-copy: byte buffers are ArraySlice<UInt8>s sharing the decoded input's storage.");
        }
        out.line("");
        out.line("import Foundation");
        out.line("");
        out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME, module.versions.is_some()));
        self.emit_constants(&mut out, module);
        for u in &module.unions {
            out.line("");
            packet::emit_union(&mut out, u, &types);
        }
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, module, p, &types);
        }
        out.buf
    }
}

/// `public let NAME: UInt8 = 1`, with the note as a doc comment.
fn const_line(out: &mut Out, c: &Constant, prefix: &str) {
    if let Some(note) = &c.note {
        out.line(format!("/// {}", note));
    }
    out.line(format!(
        "{}let {}: {} = {}",
        prefix,
        ident(&c.name.to_ascii_uppercase()),
        scalar_type(&c.ty),
        c.literal()
    ));
}

impl ConstEmitter for SwiftGenerator {
    fn constant(&self, out: &mut Out, c: &Constant) {
        const_line(out, c, "public ");
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.line(format!("/// Named `{}` values.", cat.name));
        out.open(format!("public enum {} {{", ident(&cat.name)));
        for c in &cat.members {
            const_line(out, c, "public static ");
        }
        out.close("}");
    }
}
