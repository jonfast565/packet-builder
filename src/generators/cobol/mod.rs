//! COBOL backend for GnuCOBOL (3.x, free format): one source file holding a
//! main program, the runtime and a set of programs per packet.
//!
//! A packet is a fixed-size record (`naming.rs`); its programs are
//! `P<k>-<NAME>-INIT`, `-DEC`, `-ENC`, `-JSON`, `-FREE` and, without
//! parameters, `-FRAME` and `-RUN`. Decoders and encoders are RECURSIVE
//! (packets can contain themselves through arrays); their locals live in
//! LOCAL-STORAGE. They share the runtime's EXTERNAL state record, report
//! errors in it (`PB-RC` and the message and path) and every caller checks
//! `PB-RC` after each call.
//!
//! The main program reads a LINE SEQUENTIAL `.dat` file (the path on the
//! command line, `PACKETS.DAT` by default) of lines
//! `<Packet> <hex bytes or -> [@version] [path=integer | path=#hex]...`
//! (blank lines and lines starting with `*` are skipped) and for each prints
//! the decoded value and the re-encoded bytes, then what try-decoding and
//! the frame length say, as two JSON lines.

