pub struct CobolGenerator;

const RUNTIME: &str = include_str!("../../../runtime/cobol.cob");

/// The PROGRAM-ID of the main program: the package name as a COBOL word.
pub fn main_name(opts: &GenOptions) -> String {
    let w = cob_word(&opts.package, 24);
    if w.is_empty() {
        "PACKETS".into()
    } else if w.starts_with(|c: char| c.is_ascii_digit()) || w.starts_with("PB-") || w == "PB" {
        format!("M-{}", w)
    } else {
        w
    }
}

/// `text` with every `*>@STATE` line replaced by the runtime's state record
/// (the lines between `*>@state{` and `*>@state}`).
fn paste_state(text: &str, runtime: &str) -> String {
    let start = runtime.find("*>@state{").expect("runtime has a state block");
    let start = start + runtime[start..].find('\n').expect("state block has lines") + 1;
    let end = runtime.find("*>@state}").expect("runtime has a state block end");
    let state = &runtime[start..end];
    let mut out = String::with_capacity(text.len() * 2);
    for line in text.split_inclusive('\n') {
        if line.trim() == "*>@STATE" {
            out.push_str(state);
        } else {
            out.push_str(line);
        }
    }
    out
}

impl Backend for CobolGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let runtime = runtime_source(RUNTIME, module.versions.is_some());
        let mut out = Out::new("    ");
        out.line(">>SOURCE FORMAT IS FREE");
        out.line("*> Generated by packet-builder. Do not edit.");
        out.line("*> Build: cobc -free -x <this file>; run: ./<program> [cases.dat]");
        self.emit_constants(&mut out, module);
        out.line("");
        main::main_program(&mut out, module, &main_name(opts));
        out.line("");
        // The runtime without its state block, which is pasted into every program.
        let head = runtime.find("*>@state{").expect("runtime has a state block");
        let tail = runtime.find("*>@state}").expect("runtime has a state block end");
        let tail = tail + runtime[tail..].find('\n').map(|i| i + 1).unwrap_or(0);
        out.buf.push_str(&runtime[..head]);
        out.buf.push_str(&runtime[tail..]);
        for p in &module.packets {
            packet::packet_programs(&mut out, module, p, opts.zero_copy);
        }
        paste_state(&out.buf, &runtime)
    }
}

impl ConstEmitter for CobolGenerator {
    fn open_constants(&self, out: &mut Out) {
        out.line("*> Named constants.");
    }

    fn constant(&self, out: &mut Out, c: &Constant) {
        let note = c.note.as_ref().map(|n| format!(" ({})", n)).unwrap_or_default();
        out.line(format!("*>   {} = {}{}", c.name, c.literal(), note));
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.line(format!("*> Named {} values.", cat.name));
        for c in &cat.members {
            self.constant(out, c);
        }
    }
}
