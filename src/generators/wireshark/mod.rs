//! Wireshark Lua dissectors (`packet_builder dissector`). Not a codec
//! backend: one Lua file per description that registers a protocol for each
//! `dissector` declaration.
//!
//! - `naming`: Lua identifiers and field keys, the `Lua` dialect;
//! - `expr`: `ExprLang` for Lua;
//! - `fields`: ProtoField declarations and value strings;
//! - `dissect`: the `StepEmitter` that decodes and fills the tree.

mod dissect;
mod expr;
mod fields;
mod naming;

use crate::generators::common::{Mode, Out, Scope, StepEmitter, mask, param_var, string_literal};
use crate::ir::frame::FrameLength;
use crate::ir::{Codec, Dissector, Module, Packet};
use dissect::Dissector as Emitter;
use naming::{Lua, dissect_fn};

const RUNTIME: &str = include_str!("../../../runtime/wireshark.lua");

/// The global table a generated file exports (`packet_builder_<package>`):
/// its dissect functions, for other Lua scripts and the tests.
pub fn export_name(package: &str) -> String {
    format!("packet_builder_{}", package)
}

/// The Lua file for `module`, registering `dissectors`.
pub fn generate(module: &Module, dissectors: &[Dissector], package: &str) -> String {
    let mut out = Out::new("  ");
    out.line("-- Generated by packet-builder. Do not edit.");
    out.line("--");
    out.line("-- A Wireshark (4.4 or later) Lua dissector. Load it with");
    out.line("--   wireshark -X lua_script:<this file>");
    out.line("-- or copy it into Wireshark's personal Lua plugins folder.");
    out.line("");
    out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME, module.versions.is_some()));
    fields::emit_fields(&mut out, module);
    out.line("");
    out.line("local D = {}");
    for p in &module.packets {
        out.line("");
        emit_packet(&mut out, p);
    }
    out.line("");
    out.line("-- ---- protocols ----------------------------------------------------------------");
    for d in dissectors {
        let p = module.packets.iter().find(|p| p.name == d.packet).expect("validated packet");
        let frame = module.frame_length(p);
        let frame_fn = match &frame {
            Some(f) => {
                out.line("");
                emit_frame_length(&mut out, p, f);
                format!("L_{}, {}", p.name, f.header_bytes)
            }
            None => "nil, 0".into(),
        };
        let tables: Vec<String> = d.tables.iter().map(|(t, v)| format!("{{ {}, {} }}", string_literal(t), v)).collect();
        // Files with versions: a preference for the version to dissect as.
        let latest = module.versions.map(|v| format!(", {}", v.latest)).unwrap_or_default();
        out.line("");
        out.line(format!(
            "pb_register(D, make_fields, {}, {}, {}, {{ {} }}, {}, {}{})",
            string_literal(&d.abbrev),
            string_literal(&d.name),
            string_literal(&d.packet),
            tables.join(", "),
            d.heuristic,
            frame_fn,
            latest
        ));
    }
    out.line("");
    out.line("-- For other scripts (`local M = dofile(\"this file\")`): dissect(packet, fields, experts,");
    out.line("-- tvb, tree) and register(abbrev, name, packet).");
    out.open(format!("{} = {{", export_name(package)));
    out.line("D = D,");
    out.line("make_fields = make_fields,");
    match module.versions {
        Some(v) => {
            out.line(
                "dissect = function(packet, F, X, tvb, tree, version) return pb_dissect(D, packet, F, X, tvb, tree, false, version) end,",
            );
            out.line(format!(
                "register = function(abbrev, name, packet) return pb_register(D, make_fields, abbrev, name, packet, {{}}, false, nil, 0, {}) end,",
                v.latest
            ));
        }
        None => {
            out.line(
                "dissect = function(packet, F, X, tvb, tree) return pb_dissect(D, packet, F, X, tvb, tree, false) end,",
            );
            out.line("register = function(abbrev, name, packet) return pb_register(D, make_fields, abbrev, name, packet, {}, false) end,");
        }
    }
    out.close("}");
    out.line(format!("return {}", export_name(package)));
    out.buf
}

/// `function D.Name(c, tree, label, params...)`: dissect one packet at the
/// reader's position, under a subtree labelled `label` (into `tree` itself
/// when nil); returns its values.
fn emit_packet(out: &mut Out, p: &Packet) {
    let params: String = p.params.iter().map(|x| format!(", {}", param_var(&x.name))).collect();
    out.open(format!("function {}(c, tree, label{})", dissect_fn(&p.name), params));
    out.line("local r = c.r");
    out.line("local p = {}");
    out.line("local pb_start = r.pos");
    out.line("local pb_s, pb_v, pb_c, pb_sel, pb_n, pb_j, pb_t, pb_a, pb_last");
    out.line("local t = tree");
    out.line(format!(
        "if label then t = pb_subtree(c, tree, label .. {}) end",
        string_literal(&format!(": {}", p.name))
    ));
    out.line(format!("r:enter({})", string_literal(&p.name)));
    Emitter::new(p).emit_steps(out);
    out.line("r:leave()");
    out.line("if label then pb_close(c, t, pb_start) end");
    out.line("return p");
    out.close("end");
}

/// `L_Name(tvb, pinfo, offset)`: the size of the packet at `offset` from
/// its header, for `dissect_tcp_pdus`.
fn emit_frame_length(out: &mut Out, p: &Packet, f: &FrameLength) {
    let scope = Scope::<Lua>::new(p, Mode::Decode);
    out.open(format!("local function L_{}(tvb, pinfo, offset)", p.name));
    match f.version_header {
        // The header's size depends on the version: read what is there.
        Some(_) => out.line("local r = pb_reader(tvb:raw(offset, tvb:len() - offset))"),
        None => out.line(format!("local r = pb_reader(tvb:raw(offset, {}))", f.header_bytes)),
    }
    out.line("local p = {}");
    out.line("local pb_c");
    for (fi, h) in f.fields.iter().enumerate() {
        let m = &p.members[h.member];
        // A field elsewhere in other protocol versions is read in its own.
        if let Some(c) = &h.when {
            out.open(format!("if {} then", scope.expr(c)));
        }
        out.line(format!("r.pos = {}", h.offset_bits));
        let raw = match &h.container {
            Codec::Bytes { nbytes, endian } => {
                format!("r:read_uint({}, {})", nbytes, <Lua as crate::generators::common::Dialect>::little(endian))
            }
            _ => format!("r:read_bits({})", h.container_bits),
        };
        out.line(format!("pb_c = {}", raw));
        let bits = format!("((pb_c >> {}) & 0x{:x})", h.shift, mask(h.bits));
        let v = if h.signed { format!("pb_sext({}, {})", bits, h.bits) } else { bits };
        out.line(format!("{} = {}", scope.field(m), v));
        if h.when.is_some() {
            out.close("end");
        }
        // The rest of the header, once the version field says how long it is.
        if let (0, Some(need)) = (fi, &f.version_header) {
            out.line(format!("local pb_need = {}", scope.expr(need)));
            out.line("if tvb:len() - offset < pb_need then return -(pb_need - (tvb:len() - offset)) end");
        }
    }
    for &c in &f.calcs {
        let m = &p.members[c];
        if let Some(e) = m.calc_expr() {
            out.line(format!("{} = {}", scope.field(m), expr::store_value(scope.expr(e), &m.ty)));
        }
    }
    out.line(format!("return {}", scope.expr(&f.total)));
    out.close("end");
}
