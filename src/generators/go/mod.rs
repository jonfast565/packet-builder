//! Go backend: one file, standard library only (Go 1.18+ for generics).

mod decode;
mod encode;
mod expr;
mod naming;
mod packet;

pub use naming::{field_name, member_type, scalar_type};

use crate::generators::Backend;
use crate::generators::common::{GenOptions, Out};
use crate::ir::Module;

pub struct GoGenerator;

const RUNTIME: &str = include_str!("../../../runtime/go.go");

impl Backend for GoGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let mut out = Out::new("\t");
        out.line("// Code generated by packet-builder. DO NOT EDIT.");
        out.line("");
        out.line(format!("package {}", opts.package));
        out.line("");
        out.line("import (");
        out.line("\t\"fmt\"");
        out.line("\t\"math\"");
        out.line("\t\"unicode/utf8\"");
        out.line(")");
        out.line("");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, p);
        }
        out.buf
    }
}
