//! Zig backend (Zig 0.13). Bit fields use Zig's exact-width integers (`u3`,
//! `i12`, ...), so out-of-range values are rejected by the compiler.

mod decode;
mod encode;
mod expr;
mod naming;
mod packet;

pub use naming::{ident, member_type, scalar_type};

use crate::generators::Backend;
use crate::generators::common::{GenOptions, Out};
use crate::ir::Module;

pub struct ZigGenerator;

const RUNTIME: &str = include_str!("../../../runtime/zig.zig");

impl Backend for ZigGenerator {
    fn generate(&self, module: &Module, _opts: &GenOptions) -> String {
        let mut out = Out::new("    ");
        out.line("// Generated by packet-builder. Do not edit.");
        out.line("const std = @import(\"std\");");
        out.line("");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, p);
        }
        out.buf
    }
}
