//! C# backend: one file, no dependencies beyond the base class library.

mod decode;
mod encode;
mod expr;
mod naming;
mod packet;

pub use naming::{member_type, namespace, prop_name, scalar_type};

use crate::generators::Backend;
use crate::generators::common::{GenOptions, Out};
use crate::ir::Module;

pub struct CSharpGenerator;

const RUNTIME: &str = include_str!("../../../runtime/csharp.cs");

impl Backend for CSharpGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let mut out = Out::new("    ");
        out.line("// <auto-generated> Generated by packet-builder. Do not edit. </auto-generated>");
        out.line("using System;");
        out.line("using System.Collections.Generic;");
        out.line("using System.Linq;");
        out.line("");
        out.line(format!("namespace {}", namespace(opts)));
        out.open("{");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, p);
        }
        out.close("}");
        out.buf
    }
}
