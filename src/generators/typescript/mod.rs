//! TypeScript backend: one ES module with no dependencies. It is erasable
//! TypeScript (no enums, namespaces or parameter properties), so Node runs
//! it directly and any bundler or `tsc` accepts it.

mod decode;
mod encode;
mod expr;
mod json;
mod locals;
mod naming;
mod packet;
mod stream;

pub use naming::{ident, is_big, type_name};

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out};
use crate::ir::{Category, Constant, Module};

pub struct TypeScriptGenerator;

const RUNTIME: &str = include_str!("../../../runtime/typescript.ts");

impl Backend for TypeScriptGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let mut out = Out::new("  ");
        out.line("// Generated by packet-builder. Do not edit.");
        out.line("");
        out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME, module.versions.is_some()));
        self.emit_constants(&mut out, module);
        for u in &module.unions {
            out.line("");
            packet::emit_union(&mut out, u);
        }
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, module, p, opts.zero_copy);
        }
        out.buf
    }
}

/// A constant's value as a literal of its type (`n` for wide integers).
fn literal(c: &Constant) -> String {
    naming::int_literal(&c.literal(), &c.ty)
}

impl ConstEmitter for TypeScriptGenerator {
    /// Upper case, like the Python backend.
    fn constant(&self, out: &mut Out, c: &Constant) {
        if let Some(note) = &c.note {
            out.line(format!("/** {} */", note.replace("*/", "*\\/")));
        }
        out.line(format!("export const {} = {};", naming::const_name(&c.name), literal(c)));
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.line(format!("/** Named `{}` values. */", cat.name));
        out.open(format!("export const {} = {{", type_name(&cat.name)));
        for c in &cat.members {
            if let Some(note) = &c.note {
                out.line(format!("/** {} */", note.replace("*/", "*\\/")));
            }
            out.line(format!("{}: {},", naming::const_name(&c.name), literal(c)));
        }
        out.close("} as const;");
    }
}
