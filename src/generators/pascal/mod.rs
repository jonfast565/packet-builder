//! Object Pascal backend: one unit for Free Pascal (`{$MODE DELPHIUNICODE}`)
//! and Delphi, using only SysUtils and Math.

mod decode;
mod encode;
mod expr;
mod json;
mod locals;
mod naming;
mod packet;
mod stream;

pub use naming::{ident, type_name, unit_name};

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out, const_pascal, runtime_source};
use crate::ir::{Category, Constant, Module};
use naming::scalar_type;

pub struct PascalGenerator;

const RUNTIME: &str = include_str!("../../../runtime/pascal.pas");

impl Backend for PascalGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let runtime = runtime_source(RUNTIME, module.versions.is_some());
        let split = runtime.find("// @implementation").expect("runtime has an @implementation marker");
        let (interface, rest) = runtime.split_at(split);
        let implementation = &rest[rest.find('\n').map(|i| i + 1).unwrap_or(rest.len())..];

        let mut out = Out::new("  ");
        out.line("// Generated by packet-builder. Do not edit.");
        out.line(format!("unit {};", unit_name(opts)));
        out.line("");
        out.line("{$IFDEF FPC}{$MODE DELPHIUNICODE}{$ENDIF}");
        out.line("{$Q-}");
        out.line("{$R-}");
        out.line("");
        out.line("interface");
        out.line("");
        out.line("uses");
        out.line("  SysUtils, Math;");
        out.line("");
        out.buf.push_str(interface);
        self.emit_constants(&mut out, module);
        if !module.packets.is_empty() || !module.unions.is_empty() {
            out.line("");
            out.open("type");
            let names = module.unions.iter().map(|u| &u.name).chain(module.packets.iter().map(|p| &p.name));
            for n in names.clone() {
                out.line(format!("{} = class;", type_name(n)));
            }
            for n in names {
                out.line(format!("{}Array = array of {};", type_name(n), type_name(n)));
            }
            for u in &module.unions {
                out.line("");
                packet::declare_union(&mut out, u);
            }
            for p in &module.packets {
                out.line("");
                packet::declare_packet(&mut out, module, p);
            }
            out.pop();
        }
        out.line("");
        out.line("implementation");
        out.line("");
        out.buf.push_str(implementation);
        for u in &module.unions {
            packet::implement_union(&mut out, u);
        }
        for p in &module.packets {
            packet::implement_packet(&mut out, module, p);
        }
        out.line("");
        out.line("end.");
        out.buf
    }
}

/// `Name = UInt8(1);`, with the note as a doc comment.
fn const_line(out: &mut Out, c: &Constant) {
    if let Some(note) = &c.note {
        out.line(format!("/// {}", note));
    }
    let lit = c.literal();
    let lit = match lit.strip_prefix("0x") {
        Some(hex) => format!("${}", hex),
        None => lit,
    };
    out.line(format!("{} = {}({});", ident(&const_pascal(&c.name)), scalar_type(&c.ty), lit));
}

impl ConstEmitter for PascalGenerator {
    fn open_constants(&self, out: &mut Out) {
        out.line("/// Standalone named constants.");
        out.open("const");
    }

    fn close_constants(&self, out: &mut Out) {
        out.pop();
    }

    fn constant(&self, out: &mut Out, c: &Constant) {
        const_line(out, c);
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.open("type");
        out.line(format!("/// Named {} values.", cat.name));
        out.line(format!("T{} = record", cat.name));
        out.open("const");
        for c in &cat.members {
            const_line(out, c);
        }
        out.pop();
        out.line("end;");
        out.pop();
    }
}
