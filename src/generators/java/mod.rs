//! Java backend: one file holding one class (named after the package, e.g.
//! `Packets`), with the runtime, constants, unions and packets nested in
//! it. Java 17, `java.base` only.

mod decode;
mod encode;
mod expr;
mod json;
mod naming;
mod packet;
mod stream;

pub use naming::{class_name, field_name, outer_class, scalar_type};

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out};
use crate::ir::{Category, Constant, Module};
use naming::{doc_text, int_literal};

pub struct JavaGenerator;

const RUNTIME: &str = include_str!("../../../runtime/java.java");

impl Backend for JavaGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let outer = outer_class(opts);
        let mut out = Out::new("    ");
        out.line("// Generated by packet-builder. Do not edit.");
        out.line(format!("// Save as {}.java; it has no package declaration, so add one if needed.", outer));
        out.line("");
        out.line("/** Decoders and encoders generated by packet-builder. */");
        out.line(format!("public final class {} {{", outer));
        out.line(format!("    private {}() {{}}", outer));
        out.line("");
        out.buf.push_str(&crate::generators::common::runtime_source(RUNTIME, module.versions.is_some()));
        out.push();
        self.emit_constants(&mut out, module);
        for u in &module.unions {
            out.line("");
            packet::emit_union(&mut out, u, &outer, opts.zero_copy);
        }
        for p in &module.packets {
            out.line("");
            packet::emit_packet(&mut out, module, p, opts.zero_copy, &outer);
        }
        out.pop();
        out.line("}");
        out.buf
    }
}

/// `public static final int NAME = 1;`, with the note as a doc comment.
fn const_line(out: &mut Out, c: &Constant) {
    if let Some(note) = &c.note {
        out.line(format!("/** {} */", doc_text(note)));
    }
    out.line(format!(
        "public static final {} {} = {};",
        scalar_type(&c.ty),
        const_name(&c.name),
        int_literal(&c.ty, c.value, &c.literal())
    ));
}

/// UPPER_SNAKE_CASE, as Java names constants.
fn const_name(name: &str) -> String {
    let mut out = String::new();
    let mut prev_lower = false;
    for ch in name.chars() {
        if ch.is_ascii_uppercase() && prev_lower {
            out.push('_');
        }
        prev_lower = ch.is_ascii_lowercase() || ch.is_ascii_digit();
        out.push(if ch == '-' { '_' } else { ch.to_ascii_uppercase() });
    }
    if out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, '_');
    }
    out
}

impl ConstEmitter for JavaGenerator {
    fn open_constants(&self, out: &mut Out) {
        out.line("/** Standalone named constants. */");
        out.open("public static final class Constants {");
        out.line("private Constants() {}");
        out.line("");
    }

    fn close_constants(&self, out: &mut Out) {
        out.close("}");
    }

    fn constant(&self, out: &mut Out, c: &Constant) {
        const_line(out, c);
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        let name = class_name(&cat.name);
        out.line(format!("/** Named {{@code {}}} values. */", cat.name));
        out.open(format!("public static final class {} {{", name));
        out.line(format!("private {}() {{}}", name));
        out.line("");
        for c in &cat.members {
            const_line(out, c);
        }
        out.close("}");
    }
}
