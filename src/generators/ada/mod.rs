//! Ada 2012 backend: one file holding a package spec and its body, which
//! `gnatchop` splits into `<unit>.ads` and `<unit>.adb` for GNAT. Numbers
//! are `Interfaces` types, byte buffers `Ada.Containers.Vectors`, strings
//! `Ada.Strings.Unbounded`; arrays of packets are controlled types that own
//! their elements through access values. Generated subprograms raise only
//! `Pb_Error`; `Last_Error` says what went wrong.

