pub use naming::{ident, type_name, unit_name};

use crate::generators::Backend;
use crate::generators::common::{ConstEmitter, GenOptions, Out, const_pascal, runtime_source};
use crate::ir::{Category, Constant, Module};
use naming::scalar_type;
use types::Boxes;

pub struct AdaGenerator;

const RUNTIME: &str = include_str!("../../../runtime/ada.ada");

impl Backend for AdaGenerator {
    fn generate(&self, module: &Module, opts: &GenOptions) -> String {
        let runtime = runtime_source(RUNTIME, module.versions.is_some());
        let split = runtime.find("-- @implementation").expect("runtime has an @implementation marker");
        let (spec, rest) = runtime.split_at(split);
        let implementation = &rest[rest.find('\n').map(|i| i + 1).unwrap_or(rest.len())..];
        let unit = unit_name(opts);
        let boxes = Boxes::new(module);

        let mut out = Out::new("   ");
        out.line("-- Generated by packet-builder. Do not edit.");
        out.line("");
        out.line("with Interfaces; use Interfaces;");
        out.line("with Ada.Containers.Vectors;");
        out.line("with Ada.Finalization;");
        out.line("with Ada.Strings.Unbounded;");
        out.line("");
        out.line(format!("package {} is", unit));
        out.line("");
        out.buf.push_str(spec.trim_end());
        out.buf.push('\n');
        out.push();
        self.emit_constants(&mut out, module);
        types::declare_types(&mut out, &unit, module, &boxes);
        if !module.unions.is_empty() {
            out.line("");
        }
        for u in &module.unions {
            json::declare_union_json(&mut out, u);
        }
        for p in &module.packets {
            packet::declare_packet(&mut out, module, p);
        }
        out.pop();
        out.line("");
        out.line(format!("end {};", unit));
        out.line("");
        out.line("with Ada.Exceptions;");
        out.line("with Ada.Text_IO;");
        out.line("with Ada.Unchecked_Conversion;");
        out.line("with Ada.Unchecked_Deallocation;");
        out.line("with Ada.Numerics.Generic_Elementary_Functions;");
        out.line("");
        out.line(format!("package body {} is", unit));
        out.line("");
        out.buf.push_str(implementation.trim_end());
        out.buf.push('\n');
        out.push();
        types::implement_arrays(&mut out, module);
        for u in &module.unions {
            json::implement_union_json(&mut out, u, &boxes);
        }
        for p in &module.packets {
            packet::implement_packet(&mut out, module, p, &boxes);
        }
        out.pop();
        out.line("");
        out.line(format!("end {};", unit));
        out.buf
    }
}

/// `Name : constant Unsigned_16 := 16#1F#;`, with the note as a comment.
fn const_line(out: &mut Out, c: &Constant) {
    if let Some(note) = &c.note {
        out.line(format!("--  {}", note));
    }
    let lit = c.literal();
    let lit = match lit.strip_prefix("0x") {
        Some(hex) => format!("16#{}#", hex),
        None => lit,
    };
    out.line(format!("{} : constant {} := {};", ident(&const_pascal(&c.name)), scalar_type(&c.ty), lit));
}

impl ConstEmitter for AdaGenerator {
    fn open_constants(&self, out: &mut Out) {
        out.line("--  Standalone named constants.");
    }

    fn constant(&self, out: &mut Out, c: &Constant) {
        const_line(out, c);
    }

    fn category(&self, out: &mut Out, cat: &Category) {
        out.line(format!("--  Named {} values.", cat.name));
        out.open(format!("package {} is", ident(&cat.name)));
        for c in &cat.members {
            const_line(out, c);
        }
        out.close(format!("end {};", ident(&cat.name)));
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::generators::backend;
    use crate::language::Language;

    /// Every example and spec generates a spec and a body (no Ada compiler
    /// checks them here; `tests/harness/ada.rs` does when GNAT is installed).
    #[test]
    fn generates_every_file() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"));
        let mut files = Vec::new();
        for dir in ["examples", "tests/specs"] {
            for entry in std::fs::read_dir(root.join(dir)).unwrap() {
                let path = entry.unwrap().path();
                if path.extension().is_some_and(|e| e == "packet") {
                    files.push(path);
                }
            }
        }
        assert!(!files.is_empty());
        for path in files {
            let module = crate::compile_file(&path).unwrap_or_else(|_| panic!("{} compiles", path.display()));
            let code = backend(Language::Ada).generate(&module, &GenOptions::default());
            assert!(code.contains("package Packets is"), "{}: no spec", path.display());
            assert!(code.contains("package body Packets is"), "{}: no body", path.display());
            assert!(code.contains("end Packets;"), "{}: unterminated", path.display());
            assert!(!code.contains("@implementation"), "{}: runtime marker left", path.display());
        }
    }
}
