//! Rust backend: one self-contained module, no external crates.

use crate::generators::common::{ExprLang, GenOptions, Mode, Out, emit_expr, is_calc, mask};
use crate::ir::{AggOp, ArithOp, BitPart, Codec, Count, Func, Module, Packet, Step, Ty, ValueType};
use crate::models::parsing_models::Endianness;

pub struct RustGenerator;

const RUNTIME: &str = include_str!("../../runtime/rust.rs");

const KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let",
    "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type",
    "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box", "do", "final", "macro",
    "override", "priv", "typeof", "unsized", "virtual", "yield", "try",
];

/// Rust identifier for a member name.
pub fn ident(name: &str) -> String {
    match name {
        "self" | "Self" | "super" | "crate" => format!("{}_", name),
        n if KEYWORDS.contains(&n) => format!("r#{}", n),
        n => n.to_string(),
    }
}

pub fn scalar_type(ty: &ValueType) -> String {
    match ty {
        ValueType::Int { width, signed } => {
            format!("{}{}", if *signed { "i" } else { "u" }, crate::ir::storage_for(*width))
        }
        ValueType::Float { width } => format!("f{}", width),
        ValueType::Mac => "[u8; 6]".into(),
        ValueType::Packet(n) => n.clone(),
    }
}

pub fn member_type(m: &crate::ir::Member) -> String {
    match m.array {
        Some(_) => format!("Vec<{}>", scalar_type(&m.ty)),
        None => scalar_type(&m.ty),
    }
}

impl RustGenerator {
    pub fn generate(module: &Module, _opts: &GenOptions) -> String {
        let mut out = Out::new("    ");
        out.line("// Generated by packet-builder. Do not edit.");
        out.line("#![allow(dead_code, unused_variables, unused_mut, unused_parens, non_snake_case, non_camel_case_types, clippy::all)]");
        out.line("");
        out.buf.push_str(RUNTIME);
        for p in &module.packets {
            out.line("");
            emit_packet(&mut out, p);
        }
        out.buf
    }
}

fn little(e: &Endianness) -> &'static str {
    if *e == Endianness::Le { "true" } else { "false" }
}

struct Lang<'a> {
    packet: &'a Packet,
    mode: Mode,
}

impl<'a> Lang<'a> {
    fn place(&self, member: usize) -> String {
        let m = &self.packet.members[member];
        if self.mode == Mode::Encode && is_calc(m) {
            format!("pbc_{}", m.name)
        } else {
            format!("p.{}", ident(&m.name))
        }
    }
}

impl<'a> ExprLang for Lang<'a> {
    fn int_lit(&self, v: i64) -> String {
        format!("({}i64)", v)
    }

    fn float_lit(&self, v: f64) -> String {
        format!("({:?}f64)", v)
    }

    fn member_ref(&self, member: usize, ty: Ty) -> String {
        let t = if ty == Ty::Float { "f64" } else { "i64" };
        format!("({} as {})", self.place(member), t)
    }

    fn index(&self, member: usize, index: String, ty: Ty) -> String {
        let (t, zero) = if ty == Ty::Float { ("f64", "0.0") } else { ("i64", "0") };
        format!(
            "(usize::try_from({}).ok().and_then(|i| {}.get(i)).map(|v| *v as {}).unwrap_or({}))",
            index,
            self.place(member),
            t,
            zero
        )
    }

    fn aggregate(&self, member: usize, op: AggOp, ty: Ty) -> String {
        let place = self.place(member);
        match (op, ty) {
            (AggOp::Sum, Ty::Float) => format!("{}.iter().map(|v| *v as f64).sum::<f64>()", place),
            (AggOp::Product, Ty::Float) => format!("{}.iter().map(|v| *v as f64).product::<f64>()", place),
            (AggOp::Sum, _) => format!("{}.iter().fold(0i64, |a, v| a.wrapping_add(*v as i64))", place),
            (AggOp::Product, _) => format!("{}.iter().fold(1i64, |a, v| a.wrapping_mul(*v as i64))", place),
        }
    }

    fn arith(&self, op: ArithOp, a: String, b: String, ty: Ty) -> String {
        if ty == Ty::Float {
            return match op {
                ArithOp::Add => format!("({} + {})", a, b),
                ArithOp::Sub => format!("({} - {})", a, b),
                ArithOp::Mul => format!("({} * {})", a, b),
                ArithOp::Div => format!("({} / {})", a, b),
                ArithOp::Pow => format!("{}.powf({})", a, b),
            };
        }
        match op {
            ArithOp::Add => format!("{}.wrapping_add({})", a, b),
            ArithOp::Sub => format!("{}.wrapping_sub({})", a, b),
            ArithOp::Mul => format!("{}.wrapping_mul({})", a, b),
            ArithOp::Div => format!("pb_div({}, {})", a, b),
            ArithOp::Pow => format!("pb_pow({}, {})", a, b),
        }
    }

    fn guard(&self, cond: String, then: String, other: String, _ty: Ty) -> String {
        format!("(if {} {{ {} }} else {{ {} }})", cond, then, other)
    }

    fn call(&self, func: Func, args: Vec<String>, _ty: Ty) -> String {
        match func {
            Func::Sqrt => format!("{}.sqrt()", args[0]),
            Func::Min => format!("{}.min({})", args[0], args[1]),
            Func::Max => format!("{}.max({})", args[0], args[1]),
        }
    }

    fn convert(&self, e: String, from: Ty, to: Ty) -> String {
        match (from, to) {
            (Ty::Bool, Ty::Int) => format!("({} as i64)", e),
            (Ty::Bool, Ty::Float) => format!("(({}) as i64 as f64)", e),
            (Ty::Int, Ty::Float) => format!("({} as f64)", e),
            (Ty::Float, Ty::Int) => format!("({} as i64)", e),
            (Ty::Int, Ty::Bool) => format!("({} != 0)", e),
            (Ty::Float, Ty::Bool) => format!("({} != 0.0)", e),
            _ => e,
        }
    }
}

/// Convert an i64/f64 expression to a member's storage type.
fn store_value(expr: String, ty: &ValueType) -> String {
    match ty {
        ValueType::Int { width, signed } => {
            let st = scalar_type(ty);
            if *width == crate::ir::storage_for(*width) {
                format!("({}) as {}", expr, st)
            } else {
                format!("pb_trunc({}, {}, {}) as {}", expr, width, signed, st)
            }
        }
        ValueType::Float { width } => format!("({}) as f{}", expr, width),
        _ => expr,
    }
}

/// Expression that reads one element.
fn read_elem(codec: &Codec, ty: &ValueType) -> String {
    let st = scalar_type(ty);
    let signed = ty.is_signed();
    let width = match ty {
        ValueType::Int { width, .. } => *width,
        _ => 0,
    };
    let raw = match codec {
        Codec::Bytes { nbytes, endian } => format!("pb_r.read_uint({}, {})?", nbytes, little(endian)),
        Codec::Bits { width } => format!("pb_r.read_bits({})?", width),
        Codec::Float { width: 32, endian } => {
            return format!("f32::from_bits(pb_r.read_uint(4, {})? as u32)", little(endian));
        }
        Codec::Float { endian, .. } => return format!("f64::from_bits(pb_r.read_uint(8, {})?)", little(endian)),
        Codec::Mac => return "pb_r.read_mac()?".into(),
        Codec::Packet(n) => return format!("{}::decode_from(pb_r)?", n),
    };
    if signed { format!("pb_sext({}, {}) as {}", raw, width, st) } else { format!("{} as {}", raw, st) }
}

/// Statements that write one element held in `v`.
fn write_elem(out: &mut Out, codec: &Codec, ty: &ValueType, v: &str, field: &str) {
    if let ValueType::Int { width, signed } = ty
        && ty.needs_range_check()
    {
        if *signed {
            out.line(format!("pb_check_i({} as i64, {}, \"{}\")?;", v, width, field));
        } else {
            out.line(format!("pb_check_u({} as u64, {}, \"{}\")?;", v, width, field));
        }
    }
    match codec {
        Codec::Bytes { nbytes, endian } => {
            out.line(format!("pb_w.write_uint({} as u64, {}, {});", v, nbytes, little(endian)))
        }
        Codec::Bits { width } => out.line(format!("pb_w.write_bits({} as u64, {});", v, width)),
        Codec::Float { width: 32, endian } => {
            out.line(format!("pb_w.write_uint({}.to_bits() as u64, 4, {});", v, little(endian)))
        }
        Codec::Float { endian, .. } => out.line(format!("pb_w.write_uint({}.to_bits(), 8, {});", v, little(endian))),
        Codec::Mac => out.line(format!("pb_w.write_bytes(&{});", v)),
        Codec::Packet(_) => out.line(format!("{}.encode_to(pb_w)?;", v)),
    }
}

fn emit_packet(out: &mut Out, p: &Packet) {
    let name = &p.name;

    out.line("#[derive(Debug, Clone, PartialEq, Default)]");
    out.open(format!("pub struct {} {{", name));
    for m in &p.members {
        out.line(format!("pub {}: {},", ident(&m.name), member_type(m)));
    }
    out.close("}");
    out.line("");

    out.open(format!("impl {} {{", name));

    // decode
    out.line("/// Decode from the start of `data`. Trailing bytes are ignored.");
    out.open(format!("pub fn decode(data: &[u8]) -> Result<{}, PbError> {{", name));
    out.line("let mut pb_r = PbReader::new(data);");
    out.line("Self::decode_from(&mut pb_r)");
    out.close("}");
    out.line("");
    out.open(format!("pub fn decode_from(pb_r: &mut PbReader) -> Result<{}, PbError> {{", name));
    out.line(format!("let mut p = {}::default();", name));
    let lang = Lang { packet: p, mode: Mode::Decode };
    for step in &p.steps {
        emit_decode_step(out, p, &lang, step);
    }
    out.line("Ok(p)");
    out.close("}");
    out.line("");

    // encode
    out.open("pub fn encode(&self) -> Result<Vec<u8>, PbError> {");
    out.line("let mut pb_w = PbWriter::new();");
    out.line("self.encode_to(&mut pb_w)?;");
    out.line("Ok(pb_w.finish())");
    out.close("}");
    out.line("");
    out.open("pub fn encode_to(&self, pb_w: &mut PbWriter) -> Result<(), PbError> {");
    out.line("let p = self;");
    let lang = Lang { packet: p, mode: Mode::Encode };
    for &c in &p.encode_calcs {
        let m = &p.members[c];
        if let crate::ir::MemberKind::Calculated(e) = &m.kind {
            out.line(format!(
                "let pbc_{}: {} = {};",
                m.name,
                scalar_type(&m.ty),
                store_value(emit_expr(&lang, e), &m.ty)
            ));
        }
    }
    for step in &p.steps {
        emit_encode_step(out, p, &lang, step);
    }
    out.line("Ok(())");
    out.close("}");

    out.close("}");
}

fn emit_decode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Calc { member } => {
            let m = &p.members[*member];
            if let crate::ir::MemberKind::Calculated(e) = &m.kind {
                out.line(format!("p.{} = {};", ident(&m.name), store_value(emit_expr(lang, e), &m.ty)));
            }
        }
        Step::Field { member: None, codec, array, .. } => {
            // padding
            let bits = codec.bits();
            match array {
                None => out.line(format!("pb_r.skip_bits({})?;", bits)),
                Some(Count::Expr(e)) => {
                    out.line(format!(
                        "pb_r.skip_bits(pb_count({}, {}, pb_r, \"_\")? * {})?;",
                        emit_expr(lang, e),
                        bits,
                        bits
                    ));
                }
                Some(Count::Remaining) => out.line("pb_r.skip_bits(pb_r.remaining_bits())?;"),
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let target = format!("p.{}", ident(&m.name));
            let ebits = codec.min_elem_bits();
            match array {
                None => out.line(format!("{} = {};", target, read_elem(codec, ty))),
                Some(count) => {
                    let n = match count {
                        Count::Expr(e) => format!("pb_count({}, {}, pb_r, \"{}\")?", emit_expr(lang, e), ebits, m.name),
                        Count::Remaining => String::new(),
                    };
                    if ty.is_byte() {
                        match count {
                            Count::Expr(_) => out.line(format!("{} = pb_r.read_bytes({})?;", target, n)),
                            Count::Remaining => {
                                out.line(format!("{} = pb_r.read_bytes(pb_r.remaining_bits() / 8)?;", target))
                            }
                        }
                        return;
                    }
                    match count {
                        Count::Expr(_) => {
                            out.open("{");
                            out.line(format!("let pb_n = {};", n));
                            out.line(format!("{} = Vec::with_capacity(pb_n);", target));
                            out.open("for _ in 0..pb_n {");
                            out.line(format!("{}.push({});", target, read_elem(codec, ty)));
                            out.close("}");
                            out.close("}");
                        }
                        Count::Remaining => {
                            out.open("while pb_r.remaining_bits() > 0 {");
                            out.line(format!("{}.push({});", target, read_elem(codec, ty)));
                            out.close("}");
                        }
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            out.open("{");
            let raw = match container {
                Codec::Bytes { nbytes, endian } => format!("pb_r.read_uint({}, {})?", nbytes, little(endian)),
                _ => format!("pb_r.read_bits({})?", container_width),
            };
            out.line(format!("let pb_c: u64 = {};", raw));
            for part in parts {
                emit_part_decode(out, p, part);
            }
            out.close("}");
        }
    }
}

fn emit_part_decode(out: &mut Out, p: &Packet, part: &BitPart) {
    let m = &p.members[part.member];
    let st = scalar_type(&m.ty);
    let bits = format!("((pb_c >> {}) & 0x{:x})", part.shift, mask(part.width));
    let value = if part.signed {
        format!("pb_sext({}, {}) as {}", bits, part.width, st)
    } else {
        format!("{} as {}", bits, st)
    };
    out.line(format!("p.{} = {};", ident(&m.name), value));
}

fn emit_encode_step(out: &mut Out, p: &Packet, lang: &Lang, step: &Step) {
    match step {
        Step::Calc { .. } => {}
        Step::Field { member: None, codec, array, .. } => {
            let bits = codec.bits();
            match array {
                None => out.line(format!("pb_w.write_zero_bits({});", bits)),
                Some(Count::Expr(e)) => {
                    out.line(format!("pb_w.write_zero_bits(({}).max(0) as usize * {});", emit_expr(lang, e), bits))
                }
                Some(Count::Remaining) => {}
            }
        }
        Step::Field { member: Some(mi), ty, codec, array } => {
            let m = &p.members[*mi];
            let place = format!("p.{}", ident(&m.name));
            match array {
                None => write_elem(out, codec, ty, &place, &m.name),
                Some(count) => {
                    if let Count::Expr(e) = count {
                        out.line(format!("pb_check_len({}.len(), {}, \"{}\")?;", place, emit_expr(lang, e), m.name));
                    }
                    if ty.is_byte() {
                        out.line(format!("pb_w.write_bytes(&{});", place));
                    } else {
                        out.open(format!("for pb_v in {}.iter() {{", place));
                        let v = match codec {
                            Codec::Packet(_) => "pb_v",
                            _ => "*pb_v",
                        };
                        write_elem(out, codec, ty, &format!("({})", v), &m.name);
                        out.close("}");
                    }
                }
            }
        }
        Step::Bitfield { container, container_width, parts } => {
            out.open("{");
            out.line("let mut pb_c: u64 = 0;");
            for part in parts {
                let m = &p.members[part.member];
                let place = format!("p.{}", ident(&m.name));
                if part.signed {
                    out.line(format!("pb_check_i({} as i64, {}, \"{}\")?;", place, part.width, m.name));
                } else {
                    out.line(format!("pb_check_u({} as u64, {}, \"{}\")?;", place, part.width, m.name));
                }
                out.line(format!("pb_c |= (({} as u64) & 0x{:x}) << {};", place, mask(part.width), part.shift));
            }
            match container {
                Codec::Bytes { nbytes, endian } => {
                    out.line(format!("pb_w.write_uint(pb_c, {}, {});", nbytes, little(endian)))
                }
                _ => out.line(format!("pb_w.write_bits(pb_c, {});", container_width)),
            }
            out.close("}");
        }
    }
}
